namespace Runic.Platform.Linux.DBus.Generator;

// Writes C# that uses only the public Runic.Platform.Linux.DBus API.
internal static class DBusEmitter
{
    private const string Ns = "global::Runic.Platform.Linux.DBus.";
    private const string Immutable = "global::System.Collections.Immutable.";
    private const string Values = "global::System.Collections.Immutable.ImmutableArray<" + Ns + "DBusValue>";

    internal static string Emit(GenerationUnit unit, string version)
    {
        var code = new Code();
        code.Line("// <auto-generated/>");
        code.Line($"// Generated by Runic.Platform.Linux.DBus.Generator {version} from {unit.FileName}.");
        code.Line("#nullable enable");
        code.Line("#pragma warning disable CS1591, CS0108, CS0114");
        code.Line($"namespace {unit.Namespace}");
        code.Open();
        if (unit.Service) EmitService(code, unit, version);
        else foreach (var element in unit.Interfaces) EmitProxy(code, unit, element, version);
        EmitHelpers(code);
        code.Close();
        return code.ToString();
    }

    // ---- Proxies ---------------------------------------------------------------------------------------------------

    private static void EmitProxy(Code code, GenerationUnit unit, XElement element, string version)
    {
        string iface = (string)element.Attribute("name")!;
        string name = unit.ProxyClassName(element);
        string visibility = unit.IsPublic ? "public" : "internal";
        var properties = Properties(element).ToList();
        code.Line($"/// <summary>Calls the D-Bus interface <c>{iface}</c> of one object.</summary>");
        code.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Runic.Platform.Linux.DBus.Generator\", \"{version}\")]");
        code.Line($"{visibility} sealed partial class {name} : {Ns}DBusProxy");
        code.Open();
        code.Line("/// <summary>The D-Bus interface name.</summary>");
        code.Line($"public const string InterfaceName = \"{iface}\";");
        code.Line();
        code.Line("/// <summary>Creates a proxy for the object at <paramref name=\"path\"/> of the service <paramref name=\"destination\"/>.</summary>");
        code.Line($"public {name}({Ns}DBusConnection connection, string? destination, {Ns}DBusObjectPath path) : base(connection, destination, path) {{ }}");

        foreach (var method in Members(element, "method"))
        {
            string member = MemberName(method, iface);
            var inArgs = Args(method, "in");
            var outArgs = Args(method, "out");
            var parameters = Parameters(inArgs, "options", "cancellationToken");
            code.Line();
            code.Line($"/// <summary>Calls <c>{member}</c>.</summary>");
            code.Line($"public async global::System.Threading.Tasks.ValueTask{ResultType(outArgs, "Task")} {Prettify(member)}Async({Join(parameters.Select(p => $"{CsType(p.Signature)} {p.Name}"), $"{Ns}DBusCallOptions options = {Ns}DBusCallOptions.None", "global::System.Threading.CancellationToken cancellationToken = default")})");
            code.Open();
            code.Line($"var reply = await CallAsync(InterfaceName, \"{member}\", [{string.Join(", ", parameters.Select(p => ToValue(p.Name, p.Signature)))}], options, cancellationToken).ConfigureAwait(false);");
            code.Line($"RunicDBusGenerated.Expect(reply, \"{Signature(outArgs)}\", \"{member}\");");
            if (outArgs.Count > 0) code.Line($"return {Unpack(outArgs, "reply")};");
            code.Close();
        }

        foreach (var property in properties)
        {
            string member = property.Name, type = CsType(property.Signature);
            if (property.Readable)
            {
                code.Line();
                code.Line($"/// <summary>Reads the <c>{member}</c> property.</summary>");
                code.Line($"public async global::System.Threading.Tasks.ValueTask<{type}> Get{Prettify(member)}Async(global::System.Threading.CancellationToken cancellationToken = default)");
                code.Open();
                code.Line($"var value = await GetPropertyAsync(InterfaceName, \"{member}\", cancellationToken).ConfigureAwait(false);");
                code.Line($"RunicDBusGenerated.Expect(value, \"{property.Signature}\", \"{member}\");");
                code.Line($"return {FromValue("value", property.Signature)};");
                code.Close();
            }
            if (property.Writable)
            {
                code.Line();
                code.Line($"/// <summary>Writes the <c>{member}</c> property.</summary>");
                code.Line($"public global::System.Threading.Tasks.ValueTask Set{Prettify(member)}Async({type} value, global::System.Threading.CancellationToken cancellationToken = default) =>");
                code.Line($"    SetPropertyAsync(InterfaceName, \"{member}\", {ToValue("value", property.Signature)}, cancellationToken);");
            }
        }

        code.Line();
        code.Line("/// <summary>Reads every readable property of the interface.</summary>");
        code.Line($"public async global::System.Threading.Tasks.ValueTask<{name}Properties> GetPropertiesAsync(global::System.Threading.CancellationToken cancellationToken = default) =>");
        code.Line($"    {name}Properties.Read(await GetAllPropertiesAsync(InterfaceName, cancellationToken).ConfigureAwait(false));");
        code.Line();
        code.Line("/// <summary>Reports the interface's property changes as they arrive; only changed properties are set.</summary>");
        code.Line($"public async global::System.Collections.Generic.IAsyncEnumerable<{name}Properties> WatchPropertiesAsync([global::System.Runtime.CompilerServices.EnumeratorCancellation] global::System.Threading.CancellationToken cancellationToken = default)");
        code.Open();
        code.Line("await foreach (var changes in global::System.Threading.Tasks.TaskAsyncEnumerableExtensions.ConfigureAwait(WatchPropertiesAsync(InterfaceName, cancellationToken), false))");
        code.Line($"    yield return {name}Properties.Read(changes.Changed, changes.Invalidated);");
        code.Close();

        foreach (var signal in Members(element, "signal"))
        {
            string member = MemberName(signal, iface);
            var args = Args(signal, null);
            string type = SignalType(args);
            code.Line();
            code.Line($"/// <summary>Reports each <c>{member}</c> signal of the object; the subscription starts when enumeration starts.</summary>");
            code.Line($"public async global::System.Collections.Generic.IAsyncEnumerable<{type}> Watch{Prettify(member)}Async([global::System.Runtime.CompilerServices.EnumeratorCancellation] global::System.Threading.CancellationToken cancellationToken = default)");
            code.Open();
            code.Line($"await foreach (var arguments in global::System.Threading.Tasks.TaskAsyncEnumerableExtensions.ConfigureAwait(WatchSignalAsync(InterfaceName, \"{member}\", cancellationToken), false))");
            code.Line($"    yield return Read{Prettify(member)}(arguments);");
            code.Close();
            code.Line();
            code.Line($"/// <summary>Reads the arguments of a <c>{member}</c> signal, such as one from <see cref=\"global::Runic.Platform.Linux.DBus.DBusProxy.SubscribeSignalAsync\"/>.</summary>");
            code.Line($"public static {type} Read{Prettify(member)}({Values} arguments)");
            code.Open();
            code.Line($"RunicDBusGenerated.Expect(arguments, \"{Signature(args)}\", \"{member}\");");
            code.Line(args.Count == 0 ? "return default;" : $"return {Unpack(args, "arguments")};");
            code.Close();
        }
        code.Close();
        code.Line();
        EmitPropertiesClass(code, name, iface, properties.Where(static p => p.Readable).ToList(), visibility, version);
        code.Line();
    }

    private static void EmitPropertiesClass(Code code, string name, string iface, List<Property> properties, string visibility, string version)
    {
        code.Line($"/// <summary>Properties of <c>{iface}</c>; a property the service did not send is <see langword=\"null\"/>.</summary>");
        code.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Runic.Platform.Linux.DBus.Generator\", \"{version}\")]");
        code.Line($"{visibility} sealed partial class {name}Properties");
        code.Open();
        foreach (var property in properties)
        {
            code.Line($"/// <summary>The <c>{property.Name}</c> property.</summary>");
            code.Line($"public {CsType(property.Signature)}? {Prettify(property.Name)} {{ get; private set; }}");
        }
        code.Line("/// <summary>Properties that changed without their new value.</summary>");
        code.Line("public global::System.Collections.Immutable.ImmutableArray<string> Invalidated { get; private set; } = [];");
        code.Line();
        code.Line("/// <summary>Reads properties from <c>GetAll</c> or <c>PropertiesChanged</c>; unknown names are skipped.</summary>");
        code.Line($"/// <exception cref=\"global::Runic.Platform.Linux.DBus.DBusException\">A known property has another type.</exception>");
        code.Line($"public static {name}Properties Read(global::System.Collections.Generic.IReadOnlyDictionary<string, {Ns}DBusValue> values, global::System.Collections.Immutable.ImmutableArray<string> invalidated = default)");
        code.Open();
        code.Line("global::System.ArgumentNullException.ThrowIfNull(values);");
        code.Line($"var properties = new {name}Properties {{ Invalidated = invalidated.IsDefault ? [] : invalidated }};");
        if (properties.Count > 0)
        {
            code.Line("foreach (var entry in values)");
            code.Open();
            code.Line("var value = entry.Value;");
            code.Line("switch (entry.Key)");
            code.Open();
            foreach (var property in properties)
            {
                code.Line($"case \"{property.Name}\":");
                code.Line($"    RunicDBusGenerated.Expect(value, \"{property.Signature}\", \"{property.Name}\");");
                code.Line($"    properties.{Prettify(property.Name)} = {FromValue("value", property.Signature)};");
                code.Line("    break;");
            }
            code.Close();
            code.Close();
        }
        code.Line("return properties;");
        code.Close();
        code.Close();
    }

