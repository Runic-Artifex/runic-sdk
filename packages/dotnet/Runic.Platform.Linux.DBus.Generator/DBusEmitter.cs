    private static void EmitService(Code code, GenerationUnit unit, string version)
    {
        string name = unit.ServiceClassName;
        string visibility = unit.IsPublic ? "public" : "internal";
        var interfaces = unit.Interfaces.Select(element => (Element: element, Name: (string)element.Attribute("name")!,
            Constant: Prettify(LastSegment((string)element.Attribute("name")!)) + "Interface")).ToList();
        if (interfaces.Select(static i => i.Constant).Distinct().Count() != interfaces.Count)
            throw new DBusGenerationException("Two interfaces end in the same name; set RunicDBusClassName and split them into separate files.");
        var memberNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (var (element, iface, _) in interfaces)
            foreach (var generated in Members(element, "method").Select(m => Prettify(MemberName(m, iface)) + "Async")
                .Concat(Members(element, "signal").Select(s => "Emit" + Prettify(MemberName(s, iface))))
                .Concat(Properties(element).SelectMany(p => new[] { Prettify(p.Name), "OnSet" + Prettify(p.Name) + "Async" })))
                if (!memberNames.Add(generated))
                    throw new DBusGenerationException($"The member {generated} would be generated twice; put the interfaces in separate files.");

        code.Line($"/// <summary>Answers the D-Bus interfaces {string.Join(", ", interfaces.Select(static i => $"<c>{i.Name}</c>"))}; derive from it and export it with <see cref=\"global::Runic.Platform.Linux.DBus.DBusConnection.Export\"/>.</summary>");
        code.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Runic.Platform.Linux.DBus.Generator\", \"{version}\")]");
        code.Line($"{visibility} abstract partial class {name} : {Ns}DBusObject");
        code.Open();
        code.Line("private readonly object _runicDBusGate = new();");
        foreach (var (_, iface, constant) in interfaces)
        {
            code.Line($"/// <summary>The D-Bus interface name <c>{iface}</c>.</summary>");
            code.Line($"public const string {constant} = \"{iface}\";");
        }
        code.Line();
        code.Line("/// <inheritdoc />");
        code.Line($"protected override string IntrospectionXml => @\"{string.Concat(interfaces.Select(static i => MinimizeInterfaceXml(i.Element).ToString(SaveOptions.DisableFormatting))).Replace("\"", "\"\"")}\";");

        foreach (var (element, iface, constant) in interfaces)
        {
            foreach (var method in Members(element, "method"))
            {
                string member = MemberName(method, iface);
                var parameters = Parameters(Args(method, "in"), "context");
                var outArgs = Args(method, "out");
                code.Line();
                code.Line($"/// <summary>Answers <c>{iface}.{member}</c>.</summary>");
                code.Line($"protected abstract global::System.Threading.Tasks.ValueTask{ResultType(outArgs, "Task")} {Prettify(member)}Async({Join(parameters.Select(p => $"{CsType(p.Signature)} {p.Name}"), $"{Ns}DBusMethodContext context")});");
            }
            foreach (var property in Properties(element))
            {
                string type = CsType(property.Signature), bare = Prettify(property.Name).TrimStart('@'), field = "_" + char.ToLowerInvariant(bare[0]) + bare.Substring(1);
                code.Line();
                code.Line($"private {type} {field} = {DefaultValue(property.Signature)};");
                code.Line($"/// <summary>The <c>{iface}.{property.Name}</c> property.{EmitsDoc(property)}</summary>");
                code.Line($"public {type} {Prettify(property.Name)}");
                code.Open();
                code.Line($"get {{ lock (_runicDBusGate) return {field}; }}");
                code.Line("set");
                code.Open();
                code.Line($"lock (_runicDBusGate) {field} = value;");
                // A write-only property has no value to announce.
                if (!property.Readable) { }
                else if (property.Emits == "true")
                    code.Line($"EmitPropertiesChanged({constant}, new global::System.Collections.Generic.Dictionary<string, {Ns}DBusValue> {{ [\"{property.Name}\"] = {ToValue("value", property.Signature)} }});");
                else if (property.Emits == "invalidates")
                    code.Line($"EmitPropertiesChanged({constant}, global::System.Collections.Immutable.ImmutableDictionary<string, {Ns}DBusValue>.Empty, [\"{property.Name}\"]);");
                code.Close();
                code.Close();
                if (property.Writable)
                {
                    code.Line();
                    code.Line($"/// <summary>Applies a caller's write of <c>{property.Name}</c>; the default sets <see cref=\"{Prettify(property.Name)}\"/>.</summary>");
                    code.Line($"protected virtual global::System.Threading.Tasks.ValueTask OnSet{Prettify(property.Name)}Async({type} value, {Ns}DBusMethodContext context)");
                    code.Open();
                    code.Line($"{Prettify(property.Name)} = value;");
                    code.Line("return default;");
                    code.Close();
                }
            }
            foreach (var signal in Members(element, "signal"))
            {
                string member = MemberName(signal, iface);
                var parameters = Parameters(Args(signal, null));
                code.Line();
                code.Line($"/// <summary>Emits <c>{iface}.{member}</c>; returns whether it was sent.</summary>");
                code.Line($"protected bool Emit{Prettify(member)}({string.Join(", ", parameters.Select(p => $"{CsType(p.Signature)} {p.Name}"))}) =>");
                code.Line($"    EmitSignal({constant}, \"{member}\"{string.Concat(parameters.Select(p => ", " + ToValue(p.Name, p.Signature)))});");
            }
        }

        // Method dispatch. A call without an interface matches the member on any of the object's interfaces.
        code.Line();
        code.Line("/// <inheritdoc />");
        code.Line($"protected sealed override async global::System.Threading.Tasks.ValueTask<{Values}> HandleMethodAsync({Ns}DBusMethodContext context)");
        code.Open();
        code.Line("var arguments = context.Arguments;");
        code.Line("string signature = context.Signature.Value;");
        var known = new List<(string Interface, string Member)>();
        foreach (var (element, iface, _) in interfaces)
            foreach (var method in Members(element, "method"))
            {
                string member = MemberName(method, iface);
                var inArgs = Args(method, "in");
                var outArgs = Args(method, "out");
                known.Add((iface, member));
                code.Line($"if ((context.Interface == \"{iface}\" || context.Interface.Length == 0) && context.Member == \"{member}\" && signature == \"{Signature(inArgs)}\")");
                code.Open();
                string call = $"{Prettify(member)}Async({Join(inArgs.Select((arg, index) => FromValue($"arguments[{index}]", arg.Signature)), "context")})";
                if (outArgs.Count == 0)
                {
                    code.Line($"await {call}.ConfigureAwait(false);");
                    code.Line("return [];");
                }
                else if (outArgs.Count == 1)
                {
                    code.Line($"var result = await {call}.ConfigureAwait(false);");
                    code.Line($"return [{ToValue("result", outArgs[0].Signature)}];");
                }
                else
                {
                    code.Line($"var result = await {call}.ConfigureAwait(false);");
                    code.Line($"return [{string.Join(", ", outArgs.Select((arg, index) => ToValue($"result.Item{index + 1}", arg.Signature)))}];");
                }
                code.Close();
            }
        foreach (var (iface, member) in known)
            code.Line($"if ((context.Interface == \"{iface}\" || context.Interface.Length == 0) && context.Member == \"{member}\") throw new {Ns}DBusException({Ns}DBusException.InvalidArgs, $\"{member} does not take \\\"{{signature}}\\\".\");");
        code.Line($"throw new {Ns}DBusException({Ns}DBusException.UnknownMethod, $\"No method {{context.Member}} on {{context.Interface}}.\");");
        code.Close();

        // Properties.
        code.Line();
        code.Line("/// <inheritdoc />");
        code.Line($"protected override global::System.Threading.Tasks.ValueTask<{Ns}DBusValue> GetPropertyAsync(string interfaceName, string name, {Ns}DBusMethodContext context)");
        code.Open();
        foreach (var (element, iface, _) in interfaces)
            foreach (var property in Properties(element).Where(static p => p.Readable))
                code.Line($"if (interfaceName == \"{iface}\" && name == \"{property.Name}\") return global::System.Threading.Tasks.ValueTask.FromResult({ToValue(Prettify(property.Name), property.Signature)});");
        code.Line("return base.GetPropertyAsync(interfaceName, name, context);");
        code.Close();
        code.Line();
        code.Line("/// <inheritdoc />");
        code.Line($"protected override global::System.Threading.Tasks.ValueTask<{Immutable}ImmutableDictionary<string, {Ns}DBusValue>> GetAllPropertiesAsync(string interfaceName, {Ns}DBusMethodContext context)");
        code.Open();
        foreach (var (element, iface, _) in interfaces)
        {
            var readable = Properties(element).Where(static p => p.Readable).ToList();
            if (readable.Count == 0) continue;
            code.Line($"if (interfaceName == \"{iface}\")");
            code.Open();
            code.Line($"var properties = {Immutable}ImmutableDictionary.CreateBuilder<string, {Ns}DBusValue>();");
            foreach (var property in readable) code.Line($"properties.Add(\"{property.Name}\", {ToValue(Prettify(property.Name), property.Signature)});");
            code.Line("return global::System.Threading.Tasks.ValueTask.FromResult(properties.ToImmutable());");
            code.Close();
        }
        code.Line("return base.GetAllPropertiesAsync(interfaceName, context);");
        code.Close();
        code.Line();
        code.Line("/// <inheritdoc />");
        code.Line($"protected override async global::System.Threading.Tasks.ValueTask SetPropertyAsync(string interfaceName, string name, {Ns}DBusValue value, {Ns}DBusMethodContext context)");
        code.Open();
        foreach (var (element, iface, _) in interfaces)
            foreach (var property in Properties(element))
            {
                code.Line($"if (interfaceName == \"{iface}\" && name == \"{property.Name}\")");
                code.Open();
                if (!property.Writable) code.Line($"throw new {Ns}DBusException({Ns}DBusException.PropertyReadOnly, \"{property.Name} is read-only.\");");
                else
                {
                    code.Line($"if (value.Signature.Value != \"{property.Signature}\") throw new {Ns}DBusException({Ns}DBusException.InvalidArgs, $\"{property.Name} is \\\"{property.Signature}\\\", not \\\"{{value.Signature}}\\\".\");");
                    code.Line($"await OnSet{Prettify(property.Name)}Async({FromValue("value", property.Signature)}, context).ConfigureAwait(false);");
                    code.Line("return;");
                }
                code.Close();
            }
        code.Line("await base.SetPropertyAsync(interfaceName, name, value, context).ConfigureAwait(false);");
        code.Close();
        code.Close();
        code.Line();
    }

    private static string EmitsDoc(Property property) => !property.Readable ? " Callers can only write it; setting it emits no signal." : property.Emits switch
    {
        "true" => " Setting it emits PropertiesChanged with the new value.",
        "invalidates" => " Setting it emits PropertiesChanged that invalidates it.",
        _ => " Setting it emits no signal.",
    };

    // ---- Shared helpers --------------------------------------------------------------------------------------------

    private static void EmitHelpers(Code code)
    {
        code.Line("file static class RunicDBusGenerated");
        code.Open();
        code.Line($"internal static void Expect({Values} values, string signature, string member)");
        code.Open();
        code.Line("var text = new global::System.Text.StringBuilder();");
        code.Line("foreach (var value in values) text.Append(value.Signature.Value);");
        code.Line($"if (text.ToString() != signature) throw new {Ns}DBusException({Ns}DBusException.InvalidArgs, $\"{{member}} carried \\\"{{text}}\\\", not \\\"{{signature}}\\\".\");");
        code.Close();
        code.Line($"internal static void Expect({Ns}DBusValue value, string signature, string member)");
        code.Open();
        code.Line($"if (value.Signature.Value != signature) throw new {Ns}DBusException({Ns}DBusException.InvalidArgs, $\"{{member}} is \\\"{{value.Signature}}\\\", not \\\"{{signature}}\\\".\");");
        code.Close();
        code.Close();
    }

    // ---- Interface model -------------------------------------------------------------------------------------------

    private sealed class Arg(string? name, string signature)
    {
        public string? Name { get; } = name;
        public string Signature { get; } = signature;
    }

    private sealed class Parameter(string name, string signature)
    {
        public string Name { get; } = name;
        public string Signature { get; } = signature;
    }

    private sealed class Property(string name, string signature, string access, string emits)
    {
        public string Name { get; } = name;
        public string Signature { get; } = signature;
        public bool Readable => access is "read" or "readwrite";
        public bool Writable => access is "write" or "readwrite";
        public string Emits { get; } = emits;
    }

    private static IEnumerable<XElement> Members(XElement element, string kind) => element.Elements().Where(e => e.Name.LocalName == kind);

    private static string MemberName(XElement member, string iface)
    {
        string name = (string?)member.Attribute("name") ?? "";
        if (!IsMemberName(name)) throw new DBusGenerationException($"A {member.Name.LocalName} of {iface} has the name '{name}', which is not a D-Bus member name.");
        return name;
    }

    private static List<Arg> Args(XElement member, string? direction)
    {
        var args = new List<Arg>();
        foreach (var arg in member.Elements().Where(static e => e.Name.LocalName == "arg"))
        {
            string argDirection = (string?)arg.Attribute("direction") ?? (member.Name.LocalName == "method" ? "in" : "out");
            if (direction is not null && argDirection != direction) continue;
            string signature = (string?)arg.Attribute("type") ?? "";
            if (!Signatures.IsSingleCompleteType(signature))
                throw new DBusGenerationException($"An argument of {(string?)member.Attribute("name")} has the type '{signature}', which is not one complete D-Bus type.");
            args.Add(new Arg((string?)arg.Attribute("name"), signature));
        }
        return args;
    }

    private static IEnumerable<Property> Properties(XElement element)
    {
        string defaultEmits = Annotation(element, "org.freedesktop.DBus.Property.EmitsChangedSignal") ?? "true";
        foreach (var property in Members(element, "property"))
        {
            string name = MemberName(property, (string)element.Attribute("name")!);
            string signature = (string?)property.Attribute("type") ?? "";
            if (!Signatures.IsSingleCompleteType(signature))
                throw new DBusGenerationException($"The property {name} has the type '{signature}', which is not one complete D-Bus type.");
            string access = (string?)property.Attribute("access") ?? "";
            if (access is not ("read" or "write" or "readwrite"))
                throw new DBusGenerationException($"The property {name} has the access '{access}'; use read, write or readwrite.");
            yield return new Property(name, signature, access, Annotation(property, "org.freedesktop.DBus.Property.EmitsChangedSignal") ?? defaultEmits);
        }
    }

    private static string? Annotation(XElement element, string name) =>
        element.Elements().Where(e => e.Name.LocalName == "annotation" && (string?)e.Attribute("name") == name).Select(e => (string?)e.Attribute("value")).FirstOrDefault();

    private static List<Parameter> Parameters(List<Arg> args, params string[] reserved)
    {
        var used = new HashSet<string>(reserved, StringComparer.Ordinal);
        var parameters = new List<Parameter>();
        for (int index = 0; index < args.Count; index++)
        {
            string name = args[index].Name is { Length: > 0 } argName && Prettify(argName, startWithUpper: false) is { Length: > 0 } pretty && IsIdentifier(pretty.TrimStart('@'))
                ? pretty : $"arg{index}";
            while (!used.Add(name)) name += "Value";
            parameters.Add(new Parameter(name, args[index].Signature));
        }
        return parameters;
    }

    private static string Signature(List<Arg> args) => string.Concat(args.Select(static a => a.Signature));

    private static string ResultType(List<Arg> outArgs, string _) => outArgs.Count == 0 ? "" : $"<{TupleOrSingle(outArgs)}>";

    private static string SignalType(List<Arg> args) => args.Count == 0 ? "global::Runic.Platform.PlatformUnit" : TupleOrSingle(args);

    private static string TupleOrSingle(List<Arg> args)
    {
        if (args.Count == 1) return CsType(args[0].Signature);
        var names = Parameters(args);
        return "(" + string.Join(", ", args.Select((arg, index) => $"{CsType(arg.Signature)} {Prettify(names[index].Name.TrimStart('@'))}")) + ")";
    }

    private static string Unpack(List<Arg> args, string values) => args.Count == 1 ? FromValue($"{values}[0]", args[0].Signature)
        : "(" + string.Join(", ", args.Select((arg, index) => FromValue($"{values}[{index}]", arg.Signature))) + ")";

    private static string Join(IEnumerable<string> first, params string[] rest) => string.Join(", ", first.Concat(rest));

    // ---- Type mapping ----------------------------------------------------------------------------------------------

    internal static string CsType(string signature) => signature[0] switch
    {
        'y' => "byte",
        'b' => "bool",
        'n' => "short",
        'q' => "ushort",
        'i' => "int",
        'u' => "uint",
        'x' => "long",
        't' => "ulong",
        'd' => "double",
        's' => "string",
        'o' => Ns + "DBusObjectPath",
        'g' => Ns + "DBusSignature",
        'h' => "global::System.Runtime.InteropServices.SafeHandle",
        'v' => Ns + "DBusValue",
        'a' when signature[1] == '{' => $"{Immutable}ImmutableDictionary<{CsType(signature.Substring(2, 1))}, {CsType(signature.Substring(3, signature.Length - 4))}>",
        'a' => $"{Immutable}ImmutableArray<{CsType(signature.Substring(1))}>",
        '(' => "(" + string.Join(", ", Signatures.Split(signature.Substring(1, signature.Length - 2)).Select(CsType)) + ")",
        _ => throw new DBusGenerationException($"Unsupported type '{signature}'."),
    };

    // A value every property starts with, so GetAll can answer before the object sets it: empty strings and containers.
    internal static string DefaultValue(string signature) => signature[0] switch
    {
        's' => "\"\"",
        'v' => $"{Ns}DBusValue.From(\"\")",
        'h' => "null!",
        'a' when signature[1] == '{' => $"{CsType(signature)}.Empty",
        'a' => "[]",
        '(' => "(" + string.Join(", ", Signatures.Split(signature.Substring(1, signature.Length - 2)).Select(DefaultValue)) + ")",
        _ => "default",
    };

    internal static string ToValue(string expression, string signature) => signature[0] switch
    {
        'h' => $"{Ns}DBusValue.UnixFd({expression})",
        'v' => $"{Ns}DBusValue.Variant({expression})",
        'a' when signature[1] == '{' =>
            $"{Ns}DBusValue.Dictionary(\"{signature.Substring(2, 1)}\", \"{signature.Substring(3, signature.Length - 4)}\", global::System.Linq.Enumerable.Select({expression}, static entry => global::System.Collections.Generic.KeyValuePair.Create({ToValue("entry.Key", signature.Substring(2, 1))}, {ToValue("entry.Value", signature.Substring(3, signature.Length - 4))})))",
        'a' => $"{Ns}DBusValue.Array(\"{signature.Substring(1)}\", global::System.Linq.Enumerable.Select({expression}, static item => {ToValue("item", signature.Substring(1))}))",
        '(' => $"{Ns}DBusValue.Struct({string.Join(", ", Signatures.Split(signature.Substring(1, signature.Length - 2)).Select((field, index) => ToValue($"{expression}.Item{index + 1}", field)))})",
        _ => $"{Ns}DBusValue.From({expression})",
    };

    internal static string FromValue(string expression, string signature) => signature[0] switch
    {
        'y' => $"{expression}.GetByte()",
        'b' => $"{expression}.GetBoolean()",
        'n' => $"{expression}.GetInt16()",
        'q' => $"{expression}.GetUInt16()",
        'i' => $"{expression}.GetInt32()",
        'u' => $"{expression}.GetUInt32()",
        'x' => $"{expression}.GetInt64()",
        't' => $"{expression}.GetUInt64()",
        'd' => $"{expression}.GetDouble()",
        's' => $"{expression}.GetString()",
        'o' => $"{expression}.GetObjectPath()",
        'g' => $"{expression}.GetTypeSignature()",
        'h' => $"{expression}.GetUnixFd()",
        'v' => $"{expression}.GetVariant()",
        'a' when signature[1] == '{' =>
            $"{Immutable}ImmutableDictionary.ToImmutableDictionary({expression}.GetEntries(), static entry => {FromValue("entry.Key", signature.Substring(2, 1))}, static entry => {FromValue("entry.Value", signature.Substring(3, signature.Length - 4))})",
        'a' => $"{Immutable}ImmutableArray.ToImmutableArray(global::System.Linq.Enumerable.Select({expression}.GetItems(), static item => {FromValue("item", signature.Substring(1))}))",
        '(' => StructFromValue(expression, signature),
        _ => throw new DBusGenerationException($"Unsupported type '{signature}'."),
    };

    private static string StructFromValue(string expression, string signature)
    {
        var fields = Signatures.Split(signature.Substring(1, signature.Length - 2));
        string type = CsType(signature);
        return $"((global::System.Func<{Values}, {type}>)(static fields => ({string.Join(", ", fields.Select((field, index) => FromValue($"fields[{index}]", field)))})))({expression}.GetFields())";
    }

    // ---- Names -----------------------------------------------------------------------------------------------------

    internal static string LastSegment(string interfaceName) => interfaceName.Substring(interfaceName.LastIndexOf('.') + 1);

    internal static string Prettify(string name, bool startWithUpper = true)
    {
        bool upper = startWithUpper;
        var builder = new StringBuilder(name.Length);
        bool first = true;
        foreach (char c in name)
        {
            if (c is '_' or '-')
            {
                upper = true;
                continue;
            }
            builder.Append(upper ? char.ToUpperInvariant(c) : first && !startWithUpper ? char.ToLowerInvariant(c) : c);
            upper = false;
            first = false;
        }
        string result = builder.ToString();
        return Array.IndexOf(Keywords, result) >= 0 ? "@" + result : result;
    }

    private static bool IsIdentifier(string name) => name.Length > 0 && (char.IsLetter(name[0]) || name[0] == '_') && name.All(static c => char.IsLetterOrDigit(c) || c == '_');

    internal static bool IsInterfaceName(string name)
    {
        if (name.Length is 0 or > 255) return false;
        var elements = name.Split('.');
        return elements.Length >= 2 && elements.All(static e => e.Length > 0 && !char.IsDigit(e[0]) && e.All(static c => c is (>= 'a' and <= 'z') or (>= 'A' and <= 'Z') or (>= '0' and <= '9') or '_'));
    }

    internal static bool IsMemberName(string name) => name.Length is > 0 and <= 255 && !char.IsDigit(name[0])
        && name.All(static c => c is (>= 'a' and <= 'z') or (>= 'A' and <= 'Z') or (>= '0' and <= '9') or '_');

    private static readonly string[] Keywords =
    [
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue", "decimal", "default",
        "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally", "fixed", "float", "for", "foreach", "goto",
        "if", "implicit", "in", "int", "interface", "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out",
        "override", "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc",
        "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort",
        "using", "virtual", "void", "volatile", "while",
    ];

    // The interface as introspection returns it: members, arguments and annotations, without documentation.
    private static XElement MinimizeInterfaceXml(XElement element)
    {
        var minimal = new XElement("interface", new XAttribute("name", (string)element.Attribute("name")!));
        foreach (var child in element.Elements())
        {
            string kind = child.Name.LocalName;
            if (kind is not ("method" or "signal" or "property" or "annotation")) continue;
            var copy = new XElement(kind, child.Attributes().Where(static a => !a.IsNamespaceDeclaration && a.Name.Namespace == XNamespace.None));
            foreach (var grandchild in child.Elements().Where(static e => e.Name.LocalName is "arg" or "annotation"))
                copy.Add(new XElement(grandchild.Name.LocalName, grandchild.Attributes().Where(static a => !a.IsNamespaceDeclaration && a.Name.Namespace == XNamespace.None)));
            minimal.Add(copy);
        }
        return minimal;
    }

    private sealed class Code
    {
        private readonly StringBuilder _text = new();
        private int _indent;
        public void Line(string line = "")
        {
            if (line.Length > 0) _text.Append(' ', _indent * 4).Append(line);
            _text.Append('\n');
        }
        public void Open() { Line("{"); _indent++; }
        public void Close() { _indent--; Line("}"); }
        public override string ToString() => _text.ToString();
    }
}

internal static class Signatures
{
    internal static bool IsSingleCompleteType(string signature) => signature.Length is > 0 and <= 255 && Length(signature, 0, 0, 0) == signature.Length;

    internal static List<string> Split(string signature)
    {
        var types = new List<string>();
        for (int index = 0; index < signature.Length;)
        {
            int length = Length(signature, index, 0, 0);
            if (length <= 0) throw new DBusGenerationException($"'{signature}' is not a D-Bus signature.");
            types.Add(signature.Substring(index, length));
            index += length;
        }
        return types;
    }

    private static bool IsBasic(char code) => code is 'y' or 'b' or 'n' or 'q' or 'i' or 'u' or 'x' or 't' or 'd' or 's' or 'o' or 'g' or 'h';

    private static int Length(string signature, int index, int arrays, int structs)
    {
        if (index >= signature.Length) return 0;
        char code = signature[index];
        if (IsBasic(code) || code == 'v') return 1;
        if (code == 'a')
        {
            if (arrays >= 32 || index + 1 >= signature.Length) return 0;
            if (signature[index + 1] == '{')
            {
                if (structs >= 32 || index + 2 >= signature.Length || !IsBasic(signature[index + 2])) return 0;
                int value = Length(signature, index + 3, arrays + 1, structs + 1);
                return value <= 0 || index + 3 + value >= signature.Length || signature[index + 3 + value] != '}' ? 0 : 4 + value;
            }
            int element = Length(signature, index + 1, arrays + 1, structs);
            return element <= 0 ? 0 : 1 + element;
        }
        if (code == '(')
        {
            if (structs >= 32) return 0;
            int position = index + 1, fields = 0;
            while (position < signature.Length && signature[position] != ')')
            {
                int field = Length(signature, position, arrays, structs + 1);
                if (field <= 0) return 0;
                position += field;
                fields++;
            }
            return position >= signature.Length || fields == 0 ? 0 : position + 1 - index;
        }
        return 0;
    }
}
