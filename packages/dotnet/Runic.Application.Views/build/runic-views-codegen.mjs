// Runs the Views TypeScript emitter (@runic-artifex/views/codegen) for one build (R7 G6, D080.5): reads the contract IR
// that the .NET generator wrote (obj/<configuration>/<framework>/runic-bridge/contract.ir.json), writes the generated
// clients into the generated directory, and removes the files an earlier generation wrote there that this one no
// longer writes. Runic.Application.Views.targets runs it with Node.js or Bun (RunicViewsGenerateClients):
//
//   runic-views-codegen.mjs --ir <contract.ir.json> --out <generated directory> --outputs <list file>
//     [--frontend <frontend directory>] [--frontend-unbuilt] [--bundled <emitter module>] [--emitter <emitter module>]
//     [--used-emitter <file>] [--symbols <file>] [--help-link-base <url>]
//
// The emitter is the one of the frontend's @runic-artifex/views, so that the clients match the runtime they import:
// it is resolved like a package import from the frontend directory. The bundled copy, which the Runic.Application.Views
// package carries, is used when there is no frontend (no package.json in the frontend directory), such as for a
// library or a test project, and when the build does not build the frontend (--frontend-unbuilt,
// RunicApplicationFrontendBuildEnabled=false) and the frontend has no @runic-artifex/views installed, as when a test
// project builds the application. --emitter names a module explicitly. --used-emitter records the module it used, which
// the build takes as an input.
//
// The outputs list has a line `<SHA-256> <path>` for each file written, so that the build can tell a generated file
// that was changed or removed since.
//
// A file is replaced in one rename, and only when its content changed, so a C#-only edit leaves the clients and the
// frontend build alone. Errors and warnings are printed in MSBuild's canonical form at the C# member that the IR's
// `sources` locate; the exit code is 1 after an error.
import { createHash, randomBytes } from "node:crypto";
import { closeSync, existsSync, mkdirSync, openSync, readFileSync, readSync, readdirSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, isAbsolute, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HEADER = "// <auto-generated />";
const CONTRACT_SUFFIX = ".contract.d.ts";
const NAMED_TYPES = "types.ts";
const INVOCATION = "RUNICBRIDGE001";
const NAME_COLLISION = "RUNICBRIDGE004";
const INTERNAL = "RUNICBRIDGE024";
const CLIENT_WITHOUT_PDB = "RUNICBRIDGE076";
const EMITTER = "RUNICBRIDGE084";

class Failure extends Error {
  constructor(code, message, file) {
    super(message);
    this.code = code;
    this.file = file;
  }
}

function parseArguments(argv) {
  const options = {};
  const names = new Map([["--ir", "ir"], ["--out", "out"], ["--outputs", "outputs"], ["--frontend", "frontend"],
    ["--bundled", "bundled"], ["--emitter", "emitter"], ["--used-emitter", "usedEmitter"], ["--symbols", "symbols"],
    ["--help-link-base", "helpLinkBase"]]);
  for (let index = 0; index < argv.length; index++) {
    if (argv[index] === "--frontend-unbuilt") { options.frontendUnbuilt = true; continue; }
    const name = names.get(argv[index]);
    if (name === undefined || index + 1 >= argv.length) throw new Failure(INVOCATION, `unknown or incomplete argument ${argv[index]}.`);
    options[name] = argv[++index];
  }
  for (const required of ["ir", "out", "outputs"])
    if (!options[required]) throw new Failure(INVOCATION, `--${required} is required.`);
  return options;
}

// --- The emitter ---------------------------------------------------------------------------------------------------

/** The entry of a package's `./codegen` export, for an import. */
function codegenEntry(manifest) {
  const target = manifest.exports?.["./codegen"];
  if (typeof target === "string") return target;
  return target?.import ?? target?.default;
}

/** The emitter module and a description of where it comes from. */
function resolveEmitter(options) {
  if (options.emitter) return { path: resolve(options.emitter), from: "RunicApplicationFrontendCodegenEmitter" };
  const frontend = options.frontend ? resolve(options.frontend) : null;
  if (frontend !== null && existsSync(join(frontend, "package.json"))) {
    // Node's package resolution from the frontend: node_modules in the frontend directory or any directory above it.
    for (let directory = frontend; ; directory = dirname(directory)) {
      const manifestPath = join(directory, "node_modules", "@runic-artifex", "views", "package.json");
      if (existsSync(manifestPath)) {
        const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
        const entry = codegenEntry(manifest);
        if (!entry)
          throw new Failure(EMITTER, `the frontend's @runic-artifex/views ${manifest.version ?? ""} (${dirname(manifestPath)}) has no TypeScript emitter (@runic-artifex/views/codegen), which Runic 0.24 and later generate the clients with. Update the frontend's @runic-artifex/views to the version of Runic.Application.Views.`);
        return { path: join(dirname(manifestPath), entry), from: `the frontend's @runic-artifex/views ${manifest.version ?? ""}`.trimEnd() };
      }
      if (dirname(directory) === directory) break;
    }
    if (options.frontendUnbuilt && options.bundled)
      return { path: resolve(options.bundled), from: "the copy bundled with Runic.Application.Views, since this build does not build the frontend, which has no @runic-artifex/views installed" };
    throw new Failure(EMITTER, `the frontend ${frontend} has no @runic-artifex/views installed, whose TypeScript emitter (@runic-artifex/views/codegen) generates the clients. Add @runic-artifex/views to its dependencies and install them, or let the build install them (RunicApplicationFrontendInstallEnabled).`);
  }
  if (!options.bundled) throw new Failure(EMITTER, "there is no frontend and no bundled TypeScript emitter; the Runic.Application.Views package may be incomplete.");
  return { path: resolve(options.bundled), from: "the copy bundled with Runic.Application.Views" };
}

async function loadEmitter(emitter) {
  if (!existsSync(emitter.path))
    throw new Failure(EMITTER, `the TypeScript emitter ${emitter.path} (${emitter.from}) does not exist. Build or install @runic-artifex/views.`);
  const module = await import(pathToFileURL(emitter.path).href);
  if (typeof module.generate !== "function")
    throw new Failure(EMITTER, `${emitter.path} (${emitter.from}) does not export generate().`);
  return module;
}

// --- Files ---------------------------------------------------------------------------------------------------------

function firstBytes(path, length) {
  const descriptor = openSync(path, "r");
  try {
    const buffer = Buffer.alloc(length);
    return buffer.subarray(0, readSync(descriptor, buffer, 0, length, 0)).toString("utf8");
  } finally {
    closeSync(descriptor);
  }
}

/** True for a file that starts with the header every generated module carries. */
const isGenerated = path => {
  try {
    return firstBytes(path, 64).split("\n", 1)[0].trimEnd() === HEADER;
  } catch {
    return false;
  }
};

/** True for a declaration map that the emitter wrote: `{"version":3,"file":"<name>.contract.d.ts"…`. */
const isGeneratedMap = path => {
  const name = basename(path);
  if (!name.endsWith(CONTRACT_SUFFIX + ".map")) return false;
  try {
    return firstBytes(path, 256).startsWith(`{"version":3,"file":${JSON.stringify(name.slice(0, -".map".length))}`);
  } catch {
    return false;
  }
};

const sleep = milliseconds => Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, milliseconds);

/** Writes a file in one rename when its content differs; returns whether it wrote. */
function writeIfChanged(path, content) {
  if (existsSync(path) && readFileSync(path, "utf8") === content) return false;
  mkdirSync(dirname(path), { recursive: true });
  // Frontend watchers (Vite, tsc --watch) must never observe a truncated module.
  const temporary = join(dirname(path), `.${basename(path)}.${randomBytes(8).toString("hex")}.tmp`);
  try {
    writeFileSync(temporary, content);
    // Windows refuses a rename over a file that an editor, an indexer or a virus scan holds open: retry for about 0.6 s.
    for (const delay of [20, 40, 80, 160, 320, null]) {
      try {
        renameSync(temporary, path);
        break;
      } catch (error) {
        if (delay === null || process.platform !== "win32" || !["EPERM", "EACCES", "EBUSY"].includes(error.code)) throw error;
        sleep(delay);
      }
    }
  } finally {
    rmSync(temporary, { force: true });
  }
  return true;
}

// --- RUNICBRIDGE076 ------------------------------------------------------------------------------------------------

const BASE64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

/** The names a declaration map maps: its segments with a source, which have four fields or more. */
function mappedNames(map) {
  try {
    const mappings = JSON.parse(map).mappings;
    if (typeof mappings !== "string") return 0;
    let count = 0;
    for (const line of mappings.split(";"))
      for (const segment of line.split(",").filter(part => part.length > 0))
        if ([...segment].filter(digit => { const value = BASE64.indexOf(digit); return value >= 0 && value < 32; }).length >= 4) count++;
    return count;
  } catch {
    return 0;
  }
}

/** The lines of `/** … *\/` comments that carry text. */
function documentationLines(text) {
  let count = 0;
  let inside = false;
  for (const raw of text.split("\n")) {
    let line = raw.trim();
    const opens = line.startsWith("/**");
    if (!inside && !opens) continue;
    inside = !line.endsWith("*/");
    if (opens) line = line.slice(3);
    if (line.endsWith("*/")) line = line.slice(0, -2);
    if (line.replace(/^\*+/, "").trim().length > 0) count++;
  }
  return count;
}

/**
 * RUNICBRIDGE076 (#1298): a module replaces a generated file that has more names in its declaration map or more
 * documentation lines, and an assembly of its View (any assembly for the other modules) has no PDB, so a committed
 * client would change between a build with PDBs and one without. The .NET generator names those assemblies in the
 * symbols file beside the IR.
 */
function lostSourceInformation(path, content, map, assemblies) {
  if (assemblies.length === 0 || !existsSync(path)) return null;
  const lost = [];
  try {
    if (path.endsWith(CONTRACT_SUFFIX)) {
      const before = existsSync(path + ".map") && isGeneratedMap(path + ".map") ? mappedNames(readFileSync(path + ".map", "utf8")) : 0;
      const after = map === undefined ? 0 : mappedNames(map);
      if (after < before) lost.push(after === 0 ? "its declaration map" : `${before - after} of the ${before} names in its declaration map`);
    }
    const removed = documentationLines(readFileSync(path, "utf8")) - documentationLines(content);
    if (removed > 0) lost.push(removed === 1 ? "a documentation line" : `${removed} documentation lines`);
  } catch {
    // The check only explains a change; an unreadable existing file is overwritten as before.
    return null;
  }
  if (lost.length === 0) return null;
  const named = assemblies.join(", ");
  return `the generated ${basename(path)} loses ${lost.join(" and ")} that the existing file has, because `
    + `${named} ${assemblies.length === 1 ? "has" : "have"} no PDB, through which the generator finds member locations `
    + "and the comments of partial properties. "
    + `A committed client then changes between configurations. Give ${named} a PDB in every configuration, such as `
    + "<DebugType>portable</DebugType> (or embedded), or suppress RUNICBRIDGE076 with NoWarn if the generated clients are not committed.";
}

// --- Main ----------------------------------------------------------------------------------------------------------

export async function run(argv, out = console.log, err = console.error) {
  let options = {};
  let ir = null;
  const helpLink = code => (options.helpLinkBase ? ` See ${options.helpLinkBase}${code.toLowerCase()}` : "");
  const report = (severity, code, message, file) =>
    err(`${file ? `${file}: ` : ""}${severity} ${code}: ${message}${helpLink(code)}`);
  try {
    options = parseArguments(argv);
    const irPath = resolve(options.ir);
    const outputDirectory = resolve(options.out);
    ir = JSON.parse(readFileSync(irPath, "utf8"));
    const emitter = resolveEmitter(options);
    const module = await loadEmitter(emitter);
    out(`Runic Views: generating the TypeScript clients in ${outputDirectory} with ${emitter.from} (${emitter.path}).`);

    const namedTypes = join(outputDirectory, NAMED_TYPES);
    if (existsSync(namedTypes) && !isGenerated(namedTypes))
      throw new Failure(NAME_COLLISION, `${namedTypes} is not generated, but the generator writes its named TypeScript types there. Move the file or set RunicApplicationFrontendGeneratedDirectory to a dedicated directory.`);

    let files;
    try {
      files = module.generate(ir, { outputDirectory, irDirectory: dirname(irPath) });
    } catch (error) {
      if (typeof error?.code === "string" && /^RUNICBRIDGE\d+$/.test(error.code)) throw located(error, ir, dirname(irPath));
      if (error instanceof Error && /^Not a Views contract IR of format/.test(error.message))
        throw new Failure(EMITTER, `${emitter.from} cannot read this contract IR (${ir?.format}): ${error.message} Use the @runic-artifex/views of the same version as Runic.Application.Views.`);
      throw error;
    }

    const symbols = options.symbols && existsSync(options.symbols) ? JSON.parse(readFileSync(options.symbols, "utf8")) : {};
    // The View or shared client of each module (its name without the suffix), whose assemblies count for its files.
    const owners = new Map([...(ir.sharedClients ?? []).map(client => [client.name[0].toLowerCase() + client.name.slice(1), client.id]),
      ...ir.views.map(view => [view.route, view.id])]);
    const assembliesOf = name => {
      const owner = owners.get(name.replace(/(\.mock\.ts|\.contract\.d\.ts|\.ts)$/, ""));
      return (owner === undefined ? symbols.any : symbols.owners?.[owner]) ?? [];
    };

    const written = new Set();
    for (const [name, content] of [...files].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
      const path = join(outputDirectory, name);
      if (!name.endsWith(".map")) {
        const warning = lostSourceInformation(path, content, files.get(name + ".map"), assembliesOf(name));
        if (warning !== null) report("warning", CLIENT_WITHOUT_PDB, warning, path);
      }
      writeIfChanged(path, content);
      written.add(resolve(path));
    }

    // Remove only generated files: the generated directory may hold hand-written modules. tsserver reads <file>.map
    // even without a sourceMappingURL comment, so a contract without a map loses an earlier one.
    if (existsSync(outputDirectory))
      for (const name of readdirSync(outputDirectory)) {
        const path = resolve(outputDirectory, name);
        if (written.has(path)) continue;
        if ((name.endsWith(".ts") && isGenerated(path)) || isGeneratedMap(path)) rmSync(path, { force: true });
      }
    writeIfChanged(resolve(options.outputs), [...written].sort()
      .map(path => `${createHash("sha256").update(readFileSync(path)).digest("hex")} ${path}\n`).join(""));
    if (options.usedEmitter) writeIfChanged(resolve(options.usedEmitter), emitter.path + "\n");
    return 0;
  } catch (error) {
    if (error instanceof Failure) report("error", error.code, error.message, error.file);
    else if (error?.code === "ENOENT" || error?.code === "EACCES" || error?.code === "EPERM" || error instanceof SyntaxError)
      report("error", INVOCATION, `the TypeScript emitter cannot read its input or write its output: ${error.message}`);
    else {
      report("error", INTERNAL, `internal TypeScript emitter error: ${error?.name ?? "Error"}: ${error?.message ?? error} Report it with the ViewModel that triggers it and the stack trace that follows.`);
      if (error?.stack) err(error.stack);
    }
    return 1;
  }
}

/** An emitter diagnostic at the C# member that its `sources` id locates, as the .NET generator reports one. */
function located(error, ir, irDirectory) {
  const message = error.message.startsWith(`${error.code}: `) ? error.message.slice(error.code.length + 2) : error.message;
  // The .NET generator names the ViewModel when the message does not already start with it.
  const view = error.source === undefined ? undefined
    : ir.views.find(item => error.source === item.id || error.source.startsWith(`${item.id}/`));
  const simple = view?.id.split(/[.+]/).at(-1);
  const named = view === undefined || message.startsWith(simple) || message.startsWith(view.id) ? message : `${view.id}: ${message}`;
  const location = error.source === undefined ? undefined : ir.sources?.[error.source] ?? (view ? ir.sources?.[view.id] : undefined);
  const file = location === undefined ? undefined
    : `${isAbsolute(location.file) ? location.file : resolve(irDirectory, location.file)}(${location.line},${location.column})`;
  return new Failure(error.code, named, file);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  run(process.argv.slice(2)).then(code => { process.exitCode = code; });
