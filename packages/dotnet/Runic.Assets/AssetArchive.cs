using System;
using System.Collections.Generic;
using System.IO;
using System.IO.Compression;
using System.Reflection;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Threading;
using System.Threading.Tasks;

namespace Runic.Assets;

/// <summary>Reads and writes the portable Runic Assets ZIP archive format.</summary>
public static class AssetArchive
{
    /// <summary>
    /// The archive contract written to <c>runic-assets.json</c> when no two assets have the same content. An archive
    /// that stores shared content once declares <c>runic.assets.archive/2</c>; readers accept both.
    /// </summary>
    public const string CurrentVersion = "runic.assets.archive/1";

    // Schema 2 is schema 1 plus the optional "contentPath" field: the path of another asset, with the same length and
    // SHA-256 digest, whose ZIP entry holds this asset's bytes. Such an asset has no ZIP entry of its own.
    internal const string SharedContentVersion = "runic.assets.archive/2";

    /// <summary>The default manifest-resource name generated by Runic Assets' build target.</summary>
    public const string DefaultResourceName = "Runic.Assets.StaticFiles";

    private const string ManifestEntryName = "runic-assets.json";
    private const string ContentPrefix = "assets/";

    // One asset's length is bounded by the largest .NET array, whatever AssetArchiveReadOptions allows.
    internal const long MaxAssetBytes = int.MaxValue;
    private static readonly DateTimeOffset StableTimestamp = new(1980, 1, 1, 0, 0, 0, TimeSpan.Zero);
    private static readonly System.Buffers.SearchValues<char> HexCharacters =
        System.Buffers.SearchValues.Create("0123456789abcdefABCDEF");

    /// <summary>Writes a deterministic, portable ZIP archive from one validated source.</summary>
    public static async ValueTask WriteAsync(
        IAssetSource source,
        Stream destination,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(source);
        ArgumentNullException.ThrowIfNull(destination);
        if (!destination.CanWrite)
        {
            throw new ArgumentException("The archive destination must be writable.", nameof(destination));
        }

        AssetManifest manifest = source.Manifest;
        await source.ValidateAsync(cancellationToken).ConfigureAwait(false);
        string?[] contentPaths = SharedContentPaths(manifest);
        using var archive = new ZipArchive(destination, ZipArchiveMode.Create, leaveOpen: true);
        await WriteManifestAsync(archive, manifest, contentPaths, cancellationToken).ConfigureAwait(false);

        for (int index = 0; index < contentPaths.Length; index++)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (contentPaths[index] is not null)
            {
                continue;
            }

            AssetDescriptor descriptor = manifest.Assets[index];
            ZipArchiveEntry contentEntry = archive.CreateEntry(
                ContentPrefix + descriptor.RelativePath,
                IsAlreadyCompressed(descriptor.RelativePath)
                    ? CompressionLevel.NoCompression
                    : CompressionLevel.SmallestSize);
            contentEntry.LastWriteTime = StableTimestamp;
            await using Stream output = contentEntry.Open();
            await using AssetReadSnapshot input = await source
                .OpenAsync(descriptor.RelativePath, cancellationToken)
                .ConfigureAwait(false);
            await CopyAndVerifyAsync(input.Content, output, descriptor, cancellationToken).ConfigureAwait(false);
        }
    }

    /// <summary>
    /// Writes a canonical archive from a local directory using the same manifest, validation,
    /// media-type, cache, and ZIP writer authority as every other archive producer.
    /// </summary>
    /// <remarks>
    /// This overload packs every regular file that <paramref name="excludedPaths"/> does not name, including
    /// <c>.git</c> directories and <c>.env</c> files. The overload that takes
    /// <see cref="AssetArchiveDirectoryOptions"/> leaves them out by default.
    /// </remarks>
    [System.Runtime.Versioning.SupportedOSPlatform("linux")]
    public static async ValueTask WriteDirectoryAsync(
        string sourceDirectory,
        Stream destination,
        string entryPointRelativePath = "index.html",
        IEnumerable<string>? excludedPaths = null,
        CancellationToken cancellationToken = default)
    {
        using var source = new DirectoryArchiveSource(
            sourceDirectory,
            new AssetDirectoryExclusions(entryPointRelativePath, excludedPaths, excludeDefaultPatterns: false),
            cancellationToken);
        await WriteAsync(source, destination, cancellationToken).ConfigureAwait(false);
    }

    /// <summary>
    /// Writes a canonical archive from a local directory through pinned no-follow Linux handles, with the entry
    /// point and exclusions of <paramref name="options"/>. By default <c>.git</c> directories and files whose
    /// names start with <c>.env</c> are left out at any depth.
    /// </summary>
    /// <param name="sourceDirectory">The directory to pack.</param>
    /// <param name="destination">A writable stream that receives the archive.</param>
    /// <param name="options">The entry point and the paths to leave out.</param>
    /// <param name="cancellationToken">Cancels the scan and the write.</param>
    /// <exception cref="PlatformNotSupportedException">The operating system is not Linux.</exception>
    [System.Runtime.Versioning.SupportedOSPlatform("linux")]
    public static async ValueTask WriteDirectoryAsync(
        string sourceDirectory,
        Stream destination,
        AssetArchiveDirectoryOptions options,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(options);
        using var source = new DirectoryArchiveSource(
            sourceDirectory,
            new AssetDirectoryExclusions(options),
            cancellationToken);
        await WriteAsync(source, destination, cancellationToken).ConfigureAwait(false);
    }

    /// <summary>
    /// Writes a canonical archive from a directory that the same trusted build produced, on every operating
    /// system. By default <c>.git</c> directories and files whose names start with <c>.env</c> are left out at
    /// any depth.
    /// </summary>
    /// <remarks>
    /// The directory is read with ordinary file APIs into memory before the archive is written. Symbolic links,
    /// and on Windows every reparse point such as a junction, that the scan observes are rejected with
    /// <see cref="InvalidDataException"/>. The snapshot is not safe against a process that changes the
    /// directory while it is read; use <see cref="WriteDirectoryAsync(string, Stream, AssetArchiveDirectoryOptions, CancellationToken)"/>
    /// on Linux for a directory that a less trusted process can write.
    /// </remarks>
    /// <param name="sourceDirectory">The directory to pack.</param>
    /// <param name="destination">A writable stream that receives the archive.</param>
    /// <param name="options">The entry point and the paths to leave out; <see langword="null"/> uses the defaults.</param>
    /// <param name="cancellationToken">Cancels the scan and the write.</param>
    public static async ValueTask WriteTrustedDirectoryAsync(
        string sourceDirectory,
        Stream destination,
        AssetArchiveDirectoryOptions? options = null,
        CancellationToken cancellationToken = default)
    {
        var source = new TrustedGeneratedOutputDirectorySource(
            sourceDirectory,
            new AssetDirectoryExclusions(options ?? AssetArchiveDirectoryOptions.Default),
            cancellationToken);
        await WriteAsync(source, destination, cancellationToken).ConfigureAwait(false);
    }

    /// <summary>Loads and validates a portable Runic Assets archive into memory.</summary>
    public static AssetArchiveSource Read(Stream source, AssetArchiveReadOptions? options = null)
        => ReadCore(source, options, CancellationToken.None);

    /// <summary>
    /// Loads and validates a portable Runic Assets archive into memory, reading <paramref name="source"/>
    /// asynchronously. The limits and validation are those of <see cref="Read(Stream, AssetArchiveReadOptions?)"/>.
    /// </summary>
    /// <param name="source">A readable stream positioned at the start of the archive; it need not be seekable.</param>
    /// <param name="options">The limits for untrusted input; <see langword="null"/> uses the defaults.</param>
    /// <param name="cancellationToken">Cancels the read and the validation.</param>
    /// <returns>The validated in-memory source.</returns>
    /// <exception cref="InvalidDataException">The archive is invalid or exceeds a limit of <paramref name="options"/>.</exception>
    public static async ValueTask<AssetArchiveSource> ReadAsync(
        Stream source,
        AssetArchiveReadOptions? options = null,
        CancellationToken cancellationToken = default)
    {
        options = PrepareRead(source, options);
        using var copy = new MemoryStream();
        byte[] buffer = new byte[81_920];
        long total = 0;
        int read;
        while ((read = await source.ReadAsync(buffer.AsMemory(), cancellationToken).ConfigureAwait(false)) != 0)
        {
            if (read > options.MaxArchiveBytes - total)
            {
                throw new InvalidDataException(
                    $"The asset archive exceeds the {options.MaxArchiveBytes} byte archive-size limit.");
            }

            copy.Write(buffer, 0, read);
            total += read;
        }

        cancellationToken.ThrowIfCancellationRequested();
        copy.Position = 0;
        return ReadBuffered(copy, options, cancellationToken);
    }

    private static AssetArchiveReadOptions PrepareRead(Stream source, AssetArchiveReadOptions? options)
    {
        ArgumentNullException.ThrowIfNull(source);
        if (!source.CanRead)
        {
            throw new ArgumentException("The archive source must be readable.", nameof(source));
        }

        options ??= new AssetArchiveReadOptions();
        ValidateReadOptions(options);
        return options;
    }

    private static AssetArchiveSource ReadCore(
        Stream source,
        AssetArchiveReadOptions? options,
        CancellationToken cancellationToken)
    {
        options = PrepareRead(source, options);
        using var copy = new MemoryStream();
        CopyBounded(source, copy, options.MaxArchiveBytes, cancellationToken);
        copy.Position = 0;
        return ReadBuffered(copy, options, cancellationToken);
    }

    // Reads an archive that has been copied into memory within MaxArchiveBytes: every asset is inflated and checked
    // against its SHA-256 digest before the source is returned.
    private static AssetArchiveSource ReadBuffered(
        MemoryStream copy,
        AssetArchiveReadOptions options,
        CancellationToken cancellationToken)
    {
        using var archive = new ZipArchive(copy, ZipArchiveMode.Read, leaveOpen: true);
        (AssetManifest manifest, AssetDescriptor[] descriptors, ArchiveEntryData?[] entries, string?[] contentPaths) = ReadDirectory(archive, copy, options, cancellationToken);
        // Inflate every asset now, through the slots that ReadEmbedded inflates lazily, so shared content is inflated
        // and its CRC-32 checked once, and each path is checked against its own digest.
        var content = new AssetArchiveContent(descriptors, entries, contentPaths);
        foreach (AssetDescriptor descriptor in descriptors)
        {
            cancellationToken.ThrowIfCancellationRequested();
            content.TryGet(descriptor.RelativePath, out byte[]? bytes);
            using var validation = new MemoryStream(bytes!, writable: false);
            AssetHashing.Verify(descriptor, validation);
        }

        return new AssetArchiveSource(manifest, content);
    }

    // Reads the manifest and the ZIP directory of an archive without inflating any asset (specs/assets/archive-v1.md,
    // "Reader rules"). No entry may be encrypted, and every entry must have a matching local header, bytes of its own
    // and compression method 0 or 8 (ArchiveZipLayout). The manifest must inflate to its size with a matching CRC-32
    // and be JSON of the manifest profile (UTF-8, no duplicate member names, no lone surrogates). Every declared asset
    // must have an entry of its declared length, or (schema 2) a contentPath and no entry, and the archive may hold no
    // other file. AssetArchiveContent checks that a contentPath names an asset with an entry and the same length; an
    // asset's inflated length, CRC-32 and digest are checked with its content.
    private static (AssetManifest Manifest, AssetDescriptor[] Descriptors, ArchiveEntryData?[] Entries, string?[] ContentPaths) ReadDirectory(
        ZipArchive archive,
        Stream stream,
        AssetArchiveReadOptions options,
        CancellationToken cancellationToken)
    {
        // The general-purpose flag's bit 0. An archive's entries are never encrypted, even when the data that follows
        // is plain, so the flag is invalid on every entry, directory entries included.
        foreach (ZipArchiveEntry entry in archive.Entries)
        {
            if (entry.IsEncrypted)
            {
                throw new InvalidDataException($"The asset archive entry '{entry.FullName}' is marked encrypted.");
            }
        }

        ArchiveEntryData[] located = ArchiveZipLayout.Locate(stream, archive.Entries);
        // Each entry's index in archive.Entries and located, by name.
        var entries = new Dictionary<string, int>(StringComparer.Ordinal);
        for (int index = 0; index < located.Length; index++)
        {
            cancellationToken.ThrowIfCancellationRequested();
            string name = located[index].Name;
            if (name.EndsWith('/'))
            {
                continue;
            }

            if (!entries.TryAdd(name, index))
            {
                throw new InvalidDataException($"The asset archive contains duplicate entry '{name}'.");
            }
        }

        if (!entries.Remove(ManifestEntryName, out int manifestIndex))
        {
            throw new InvalidDataException("The asset archive does not contain runic-assets.json.");
        }

        long manifestLength = archive.Entries[manifestIndex].Length;
        long manifestLimit = Math.Min(options.MaxManifestBytes, MaxAssetBytes);
        if (manifestLength > manifestLimit)
        {
            throw new InvalidDataException($"The asset archive manifest exceeds the {manifestLimit} byte limit.");
        }

        byte[] manifestBytes = Inflate(located[manifestIndex], manifestLength, "The asset archive manifest");

        // JsonDocument checks the UTF-8 of a string only when it is read, so a member the reader ignores could carry
        // bytes that are not UTF-8.
        if (!System.Text.Unicode.Utf8.IsValid(manifestBytes))
        {
            throw new InvalidDataException("The asset archive manifest is not valid JSON: it is not UTF-8.");
        }

        cancellationToken.ThrowIfCancellationRequested();
        AssetDescriptor[] descriptors;
        string?[] contentPaths;
        using (JsonDocument document = ParseManifest(manifestBytes))
        {
            cancellationToken.ThrowIfCancellationRequested();
            JsonElement root = document.RootElement;
            if (root.ValueKind != JsonValueKind.Object
                || !root.TryGetProperty("version", out JsonElement version)
                || !root.TryGetProperty("assets", out JsonElement assets)
                || assets.ValueKind != JsonValueKind.Array)
            {
                throw new InvalidDataException("The asset archive manifest has an unsupported shape or version.");
            }

            string? versionName = version.ValueKind == JsonValueKind.String ? version.GetString() : null;
            bool sharedContent = StringComparer.Ordinal.Equals(versionName, SharedContentVersion);
            if (!sharedContent && !StringComparer.Ordinal.Equals(versionName, CurrentVersion))
            {
                throw new InvalidDataException("The asset archive manifest has an unsupported shape or version.");
            }
            var parsed = new List<AssetDescriptor>();
            var parsedContentPaths = new List<string?>();
            long totalLength = 0;
            foreach (JsonElement asset in assets.EnumerateArray())
            {
                cancellationToken.ThrowIfCancellationRequested();
                if (parsed.Count >= options.MaxFileCount)
                {
                    throw new InvalidDataException(
                        $"The asset archive exceeds the {options.MaxFileCount} file limit.");
                }

                try
                {
                    var descriptor = new AssetDescriptor(
                        asset.GetProperty("path").GetString()!,
                        asset.GetProperty("mediaType").GetString()!,
                        asset.GetProperty("length").GetInt64(),
                        asset.GetProperty("sha256").GetString()!,
                        asset.GetProperty("entryPoint").GetBoolean(),
                        ParseCacheMode(asset.GetProperty("cacheMode").GetString()!));
                    if (descriptor.Length > MaxAssetBytes)
                    {
                        throw new InvalidDataException(
                            $"Asset '{descriptor.RelativePath}' exceeds the {MaxAssetBytes} byte asset-size limit.");
                    }

                    if (descriptor.Length > options.MaxTotalUncompressedBytes - totalLength)
                    {
                        throw new InvalidDataException(
                            $"The asset archive exceeds the {options.MaxTotalUncompressedBytes} byte uncompressed-size limit.");
                    }

                    string? contentPath = null;
                    if (asset.TryGetProperty("contentPath", out JsonElement contentPathElement))
                    {
                        // Schema 1 has no shared content: a schema-1 reader would look for an entry that is not there.
                        if (!sharedContent)
                        {
                            throw new InvalidDataException(
                                "The asset archive manifest declares shared content but not schema runic.assets.archive/2.");
                        }

                        contentPath = AssetPath.Normalize(contentPathElement.GetString()!);
                    }

                    totalLength += descriptor.Length;
                    parsed.Add(descriptor);
                    parsedContentPaths.Add(contentPath);
                }
                catch (Exception exception) when (exception is ArgumentException or FormatException or InvalidOperationException or KeyNotFoundException)
                {
                    throw new InvalidDataException("The asset archive manifest contains invalid asset metadata.", exception);
                }
            }

            descriptors = parsed.ToArray();
            contentPaths = parsedContentPaths.ToArray();
        }

        // Unique paths and exactly one entry point, before the entries are matched to the paths.
        AssetManifest manifest;
        try
        {
            manifest = new AssetManifest(descriptors);
        }
        catch (ArgumentException exception)
        {
            throw new InvalidDataException("The asset archive manifest is invalid: " + exception.Message, exception);
        }

        var contentEntries = new ArchiveEntryData?[descriptors.Length];
        for (int index = 0; index < descriptors.Length; index++)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (contentPaths[index] is not null)
            {
                continue;
            }

            AssetDescriptor descriptor = descriptors[index];
            string entryName = ContentPrefix + descriptor.RelativePath;
            if (!entries.Remove(entryName, out int entryIndex))
            {
                throw new InvalidDataException($"The asset archive is missing '{descriptor.RelativePath}'.");
            }

            long entryLength = archive.Entries[entryIndex].Length;
            if (entryLength != descriptor.Length)
            {
                throw new InvalidDataException(
                    $"Asset '{descriptor.RelativePath}' has a ZIP entry of {entryLength} bytes, not its length {descriptor.Length}.");
            }

            contentEntries[index] = located[entryIndex];
        }

        // An asset with contentPath has no entry of its own: one would be left here.
        if (entries.Count != 0)
        {
            throw new InvalidDataException("The asset archive contains undeclared files.");
        }

        return (manifest, descriptors, contentEntries, contentPaths);
    }

    // A cache mode is one of its three names, compared ordinally: not a number, a flag list, another case or padded.
    private static AssetCacheMode ParseCacheMode(string name) => name switch
    {
        nameof(AssetCacheMode.NoStore) => AssetCacheMode.NoStore,
        nameof(AssetCacheMode.Revalidate) => AssetCacheMode.Revalidate,
        nameof(AssetCacheMode.Immutable) => AssetCacheMode.Immutable,
        _ => throw new FormatException("An asset's cacheMode must be NoStore, Revalidate or Immutable."),
    };

    // The writer's choice of shared content: each asset whose length and digest an earlier asset (in ordinal path
    // order) already has names that asset's path; the others, and every asset of an archive without duplicates, null.
    internal static string?[] SharedContentPaths(AssetManifest manifest)
    {
        var contentPaths = new string?[manifest.Assets.Count];
        var stored = new Dictionary<string, AssetDescriptor>(StringComparer.Ordinal);
        for (int index = 0; index < contentPaths.Length; index++)
        {
            AssetDescriptor descriptor = manifest.Assets[index];
            if (stored.TryGetValue(descriptor.Sha256, out AssetDescriptor? holder) && holder.Length == descriptor.Length)
            {
                contentPaths[index] = holder.RelativePath;
            }
            else
            {
                stored.TryAdd(descriptor.Sha256, descriptor);
            }
        }

        return contentPaths;
    }

    // Inflates one entry whose directory length ReadDirectory checked, at most MaxAssetBytes. The entry must hold
    // exactly that many bytes, read on past them to find that its data ends there, with the CRC-32 that the central
    // directory records, in eager and lazy reads alike: a damaged entry is never served.
    internal static byte[] Inflate(ArchiveEntryData entry, long length, string subject)
    {
        byte[] bytes = new byte[checked((int)length)];
        using Stream input = entry.Open();
        int total = 0;
        int read;
        while (total < bytes.Length && (read = input.Read(bytes, total, bytes.Length - total)) != 0)
        {
            total += read;
        }

        if (total != bytes.Length)
        {
            throw new InvalidDataException($"{subject} has {total} bytes in its ZIP entry, not its length {length}.");
        }

        if (input.ReadByte() != -1)
        {
            throw new InvalidDataException($"{subject} has more bytes in its ZIP entry than its length {length}.");
        }

        if (AssetHashing.Crc32(bytes) != entry.Crc32)
        {
            throw new InvalidDataException($"{subject} does not match its ZIP entry's CRC-32.");
        }

        return bytes;
    }

    /// <summary>
    /// Loads a canonical Runic Assets archive from an assembly manifest resource. The manifest and the ZIP directory
    /// are read and checked at once; each asset is inflated when it is first opened and then kept in memory.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Since 0.15 an embedded archive is not checked against its SHA-256 digests when it is loaded or opened. It is
    /// part of the assembly that holds the application's code, so whoever can change its bytes can change that code
    /// too, and the Runic.Assets build verified it when it packed or embedded it (<c>RunicAssetsDist</c>,
    /// <c>RunicAssetsEmbeddedArchive</c>). An asset whose inflated length differs from its declared length, whose
    /// ZIP entry is damaged, or whose bytes do not match the CRC-32 of its ZIP entry (since 0.24) fails to open with
    /// <see cref="InvalidDataException"/>, so a damaged entry is never served.
    /// </para>
    /// <para>
    /// <see cref="AssetArchiveSource.ValidateAsync"/> checks every asset against its digest on demand, for a resource
    /// that another build step embedded. <see cref="Read(Stream, AssetArchiveReadOptions?)"/> and
    /// <see cref="ReadAsync"/>, which read an archive from outside the assembly such as a file, check every digest
    /// before they return.
    /// </para>
    /// </remarks>
    /// <param name="assembly">The assembly that holds the resource.</param>
    /// <param name="resourceName">The manifest resource name; <see cref="DefaultResourceName"/> by default.</param>
    /// <param name="options">The limits; <see langword="null"/> uses the defaults.</param>
    /// <returns>The source, which reads its assets from the resource.</returns>
    /// <exception cref="ArgumentException">The assembly has no such resource.</exception>
    /// <exception cref="InvalidDataException">The manifest or the ZIP directory is invalid or exceeds a limit of
    /// <paramref name="options"/>.</exception>
    public static AssetArchiveSource ReadEmbedded(
        Assembly assembly,
        string resourceName = DefaultResourceName,
        AssetArchiveReadOptions? options = null)
    {
        ArgumentNullException.ThrowIfNull(assembly);
        ArgumentException.ThrowIfNullOrWhiteSpace(resourceName);

        Stream stream = assembly.GetManifestResourceStream(resourceName)
            ?? throw new ArgumentException(
                $"Assembly '{assembly.GetName().Name}' does not contain manifest resource '{resourceName}'.",
                nameof(resourceName));
        return ReadInPlace(stream, options);
    }

    // ReadEmbedded's reader: checks the manifest and the ZIP directory, and inflates each asset on first use without
    // checking its digest. The source owns stream from here on.
    internal static AssetArchiveSource ReadInPlace(Stream stream, AssetArchiveReadOptions? options)
    {
        ZipArchive? archive = null;
        try
        {
            options = PrepareRead(stream, options);
            // A manifest resource is mapped with the assembly, so the archive reads it in place. A resource stream
            // that cannot seek is copied first, within the same limit.
            if (!stream.CanSeek)
            {
                var copy = new MemoryStream();
                CopyBounded(stream, copy, options.MaxArchiveBytes, CancellationToken.None);
                copy.Position = 0;
                stream.Dispose();
                stream = copy;
            }
            else if (stream.Length > options.MaxArchiveBytes)
            {
                throw new InvalidDataException(
                    $"The asset archive exceeds the {options.MaxArchiveBytes} byte archive-size limit.");
            }

            archive = new ZipArchive(stream, ZipArchiveMode.Read, leaveOpen: false);
            (AssetManifest manifest, AssetDescriptor[] descriptors, ArchiveEntryData?[] entries, string?[] contentPaths) = ReadDirectory(archive, stream, options, CancellationToken.None);
            return new AssetArchiveSource(manifest, new AssetArchiveContent(descriptors, entries, contentPaths));
        }
        catch
        {
            if (archive is not null)
            {
                archive.Dispose();
            }
            else
            {
                stream.Dispose();
            }

            throw;
        }
    }

    /// <summary>Validates an archive and returns its canonical, deterministic manifest inspection.</summary>
    public static AssetArchiveInspection Inspect(Stream source, AssetArchiveReadOptions? options = null)
    {
        AssetArchiveSource archive = ReadCore(source, options, CancellationToken.None);
        string?[] contentPaths = SharedContentPaths(archive.Manifest);
        return new AssetArchiveInspection(
            archive.Manifest,
            SerializeManifest(archive.Manifest, contentPaths),
            ManifestVersion(contentPaths));
    }

    private static async ValueTask WriteManifestAsync(
        ZipArchive archive,
        AssetManifest manifest,
        string?[] contentPaths,
        CancellationToken cancellationToken)
    {
        ZipArchiveEntry manifestEntry = archive.CreateEntry(ManifestEntryName, CompressionLevel.SmallestSize);
        manifestEntry.LastWriteTime = StableTimestamp;
        await using Stream manifestStream = manifestEntry.Open();
        using var writer = new Utf8JsonWriter(manifestStream, new JsonWriterOptions { Indented = false });
        WriteManifest(writer, manifest, contentPaths);
        await writer.FlushAsync(cancellationToken).ConfigureAwait(false);
    }

    // An archive without shared content is written exactly as schema 1, so older readers still load it.
    private static string ManifestVersion(string?[] contentPaths) =>
        Array.Exists(contentPaths, static path => path is not null) ? SharedContentVersion : CurrentVersion;

    private static void WriteManifest(Utf8JsonWriter writer, AssetManifest manifest, string?[] contentPaths)
    {
        writer.WriteStartObject();
        writer.WriteString("version", ManifestVersion(contentPaths));
        writer.WriteStartArray("assets");
        for (int index = 0; index < contentPaths.Length; index++)
        {
            AssetDescriptor descriptor = manifest.Assets[index];
            writer.WriteStartObject();
            writer.WriteString("path", descriptor.RelativePath);
            writer.WriteString("mediaType", descriptor.MediaType);
            writer.WriteNumber("length", descriptor.Length);
            writer.WriteString("sha256", descriptor.Sha256);
            writer.WriteBoolean("entryPoint", descriptor.IsEntryPoint);
            writer.WriteString("cacheMode", descriptor.CacheMode.ToString());
            if (contentPaths[index] is string contentPath)
            {
                writer.WriteString("contentPath", contentPath);
            }

            writer.WriteEndObject();
        }

        writer.WriteEndArray();
        writer.WriteEndObject();
    }

    private static byte[] SerializeManifest(AssetManifest manifest, string?[] contentPaths)
    {
        using var stream = new MemoryStream();
        using (var writer = new Utf8JsonWriter(stream, new JsonWriterOptions { Indented = false }))
        {
            WriteManifest(writer, manifest, contentPaths);
        }

        return stream.ToArray();
    }

    // Only content-addressed file names may be cached forever. Unhashed files such as favicon.ico,
    // robots.txt, manifest.webmanifest or sw.js keep their URL across releases and must revalidate.
    internal static AssetCacheMode InferCacheMode(string relativePath)
    {
        string name = relativePath[(relativePath.LastIndexOf('/') + 1)..];
        string extension = Path.GetExtension(name);
        if (extension.Equals(".html", StringComparison.OrdinalIgnoreCase)
            || extension.Equals(".htm", StringComparison.OrdinalIgnoreCase))
        {
            return AssetCacheMode.Revalidate;
        }

        // Check "name-hash.js" and, for derived files, "name-hash.js.map".
        string stem = name[..^extension.Length];
        return HasHashSegment(stem) || HasHashSegment(Path.GetFileNameWithoutExtension(stem))
            ? AssetCacheMode.Immutable
            : AssetCacheMode.Revalidate;
    }

    // Recognizes "[name]-[hash]" and "[name].[hash]" with the eight-character base64url hashes emitted
    // by Rollup/Vite, SvelteKit and esbuild/Angular, plus "[name].[hash]" with webpack's hex hashes.
    private static bool HasHashSegment(string stem)
    {
        const int HashLength = 8;
        int dot = stem.LastIndexOf('.');
        if (dot > 0)
        {
            ReadOnlySpan<char> segment = stem.AsSpan(dot + 1);
            if ((segment.Length == HashLength && IsHash(segment))
                || (segment.Length >= 2 * HashLength && !segment.ContainsAnyExcept(HexCharacters) && IsHash(segment)))
            {
                return true;
            }
        }

        return stem.Length > HashLength + 1
            && stem[^(HashLength + 1)] == '-'
            && IsHash(stem.AsSpan(stem.Length - HashLength));
    }

    // A hash contains a digit and a letter, so words such as "SemiBold" and dates such as
    // "20240101" are not mistaken for content hashes. A missed hash only costs revalidation.
    private static bool IsHash(ReadOnlySpan<char> segment)
    {
        bool digit = false;
        bool letter = false;
        foreach (char character in segment)
        {
            if (char.IsAsciiDigit(character))
            {
                digit = true;
            }
            else if (char.IsAsciiLetter(character))
            {
                letter = true;
            }
            else if (character is not ('-' or '_'))
            {
                return false;
            }
        }

        return digit && letter;
    }

    private static bool IsAlreadyCompressed(string path) =>
        Path.GetExtension(path).ToLowerInvariant() is
            ".7z" or ".avif" or ".br" or ".gif" or ".gz" or ".ico" or ".jpeg" or ".jpg"
            or ".mp3" or ".mp4" or ".ogg" or ".opus" or ".pdf" or ".png" or ".rar"
            or ".webm" or ".webp" or ".woff" or ".woff2" or ".zip";

    // The manifest profile: one UTF-8 JSON text (RFC 8259), after at most one byte order mark, nested at most 64 deep,
    // no object with two members of the same name (compared after unescaping), and no string with a lone surrogate
    // escape, in the members that the reader ignores too (I-JSON, RFC 7493).
    private static readonly JsonDocumentOptions ManifestJsonOptions = new() { AllowDuplicateProperties = false };

    private static JsonDocument ParseManifest(byte[] manifest)
    {
        ReadOnlyMemory<byte> json = manifest;
        if (json.Span.StartsWith("\uFEFF"u8))
        {
            json = json[3..];
        }

        try
        {
            // JsonDocument unescapes a string only when it is read, so one that the reader ignores is checked here.
            var reader = new Utf8JsonReader(json.Span, new JsonReaderOptions { MaxDepth = ManifestJsonOptions.MaxDepth });
            while (reader.Read())
            {
                if (reader.TokenType is JsonTokenType.PropertyName or JsonTokenType.String && reader.ValueIsEscaped)
                {
                    _ = reader.GetString();
                }
            }

            return JsonDocument.Parse(json, ManifestJsonOptions);
        }
        catch (JsonException exception)
        {
            throw new InvalidDataException("The asset archive manifest is not valid JSON.", exception);
        }
        catch (InvalidOperationException exception)
        {
            // Utf8JsonReader.GetString's failure for an escape that is not a whole UTF-16 character.
            throw new InvalidDataException("The asset archive manifest is not valid JSON: a string has a lone surrogate.", exception);
        }
    }

    private static void ValidateReadOptions(AssetArchiveReadOptions options)
    {
        ArgumentOutOfRangeException.ThrowIfLessThan(options.MaxFileCount, 1);
        ArgumentOutOfRangeException.ThrowIfLessThan(options.MaxArchiveBytes, 1);
        ArgumentOutOfRangeException.ThrowIfLessThan(options.MaxTotalUncompressedBytes, 1);
        ArgumentOutOfRangeException.ThrowIfLessThan(options.MaxManifestBytes, 1);
    }

    private static async ValueTask CopyAndVerifyAsync(
        Stream input,
        Stream output,
        AssetDescriptor descriptor,
        CancellationToken cancellationToken)
    {
        using IncrementalHash hash = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
        byte[] buffer = new byte[81_920];
        long total = 0;
        int read;
        while ((read = await input.ReadAsync(buffer.AsMemory(), cancellationToken).ConfigureAwait(false)) != 0)
        {
            if (read > descriptor.Length - total)
            {
                throw new InvalidDataException($"Asset '{descriptor.RelativePath}' exceeded its declared length.");
            }

            hash.AppendData(buffer, 0, read);
            await output.WriteAsync(buffer.AsMemory(0, read), cancellationToken).ConfigureAwait(false);
            total += read;
        }

        if (total != descriptor.Length
            || !StringComparer.Ordinal.Equals(
                Convert.ToHexStringLower(hash.GetHashAndReset()),
                descriptor.Sha256))
        {
            throw new InvalidDataException($"Asset '{descriptor.RelativePath}' changed while its archive was written.");
        }
    }

    private static void CopyBounded(
        Stream source,
        Stream destination,
        long maximumBytes,
        CancellationToken cancellationToken)
    {
        byte[] buffer = new byte[81_920];
        long total = 0;
        int read;
        while ((read = source.Read(buffer, 0, buffer.Length)) != 0)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (read > maximumBytes - total)
            {
                throw new InvalidDataException(
                    $"The asset archive exceeds the {maximumBytes} byte archive-size limit.");
            }

            destination.Write(buffer, 0, read);
            total += read;
        }
    }

    [System.Runtime.Versioning.SupportedOSPlatform("linux")]
    private sealed class DirectoryArchiveSource : IAssetSource, IDisposable
    {
        private readonly PosixAssetRoot _root;
        private readonly AssetDirectoryExclusions _exclusions;

        internal DirectoryArchiveSource(
            string sourceDirectory,
            AssetDirectoryExclusions exclusions,
            CancellationToken cancellationToken)
        {
            if (!OperatingSystem.IsLinux())
            {
                throw new PlatformNotSupportedException(
                    "Directory archive compilation is supported on Linux only because it requires no-follow directory handles.");
            }

            ArgumentException.ThrowIfNullOrWhiteSpace(sourceDirectory);
            _exclusions = exclusions;
            _root = new PosixAssetRoot(Path.GetFullPath(sourceDirectory));
            try
            {
                Manifest = Scan(exclusions.EntryPoint, cancellationToken);
            }
            catch
            {
                _root.Dispose();
                throw;
            }
        }

        public AssetManifest Manifest { get; }

        public ValueTask ValidateAsync(CancellationToken cancellationToken = default)
        {
            foreach (AssetDescriptor descriptor in Manifest.Assets)
            {
                cancellationToken.ThrowIfCancellationRequested();
                using FileStream stream = OpenFile(descriptor.RelativePath);
                AssetHashing.Verify(descriptor, stream);
            }

            return ValueTask.CompletedTask;
        }

        public ValueTask<AssetReadSnapshot> OpenAsync(
            string relativePath,
            CancellationToken cancellationToken = default)
        {
            cancellationToken.ThrowIfCancellationRequested();
            string path = AssetPath.Normalize(relativePath);
            if (!Manifest.TryGetAsset(path, out AssetDescriptor? descriptor))
            {
                throw new FileNotFoundException("The requested asset is not declared by the archive manifest.", path);
            }

            return ValueTask.FromResult(new AssetReadSnapshot(descriptor, OpenFile(path)));
        }

        public void Dispose() => _root.Dispose();

        private AssetManifest Scan(string entryPoint, CancellationToken cancellationToken)
        {
            var descriptors = new List<AssetDescriptor>();
            var pending = new Stack<string>();
            pending.Push("");
            while (pending.Count != 0)
            {
                cancellationToken.ThrowIfCancellationRequested();
                string directory = pending.Pop();
                foreach (string name in _root.EnumerateEntries(directory))
                {
                    cancellationToken.ThrowIfCancellationRequested();
                    string relativePath = directory.Length == 0 ? name : directory + "/" + name;
                    relativePath = AssetPath.Normalize(relativePath);
                    if (_root.IsDirectory(relativePath))
                    {
                        if (!_exclusions.ExcludesDirectory(name))
                        {
                            pending.Push(relativePath);
                        }

                        continue;
                    }

                    if (_exclusions.ExcludesFile(relativePath, name))
                    {
                        continue;
                    }

                    using FileStream stream = OpenFile(relativePath);
                    descriptors.Add(AssetHashing.Describe(
                        relativePath,
                        stream,
                        mediaType: null,
                        StringComparer.Ordinal.Equals(relativePath, entryPoint),
                        InferCacheMode(relativePath)));
                }
            }

            return new AssetManifest(descriptors);
        }

        private FileStream OpenFile(string relativePath)
        {
            return _root.OpenRead(AssetPath.Normalize(relativePath));
        }
    }

    private sealed class TrustedGeneratedOutputDirectorySource : IAssetSource
    {
        private readonly Dictionary<string, byte[]> _contents;

        internal TrustedGeneratedOutputDirectorySource(
            string sourceDirectory,
            AssetDirectoryExclusions exclusions,
            CancellationToken cancellationToken)
        {
            ArgumentException.ThrowIfNullOrWhiteSpace(sourceDirectory);
            string root = Path.GetFullPath(sourceDirectory);
            var rootInfo = new DirectoryInfo(root);
            if (!rootInfo.Exists)
            {
                throw new DirectoryNotFoundException($"Asset source directory '{root}' does not exist.");
            }

            ThrowIfLink(rootInfo);
            _contents = Scan(rootInfo, exclusions, cancellationToken, out AssetManifest manifest);
            Manifest = manifest;
        }

        public AssetManifest Manifest { get; }

        public ValueTask ValidateAsync(CancellationToken cancellationToken = default)
        {
            cancellationToken.ThrowIfCancellationRequested();
            return ValueTask.CompletedTask;
        }

        public ValueTask<AssetReadSnapshot> OpenAsync(
            string relativePath,
            CancellationToken cancellationToken = default)
        {
            cancellationToken.ThrowIfCancellationRequested();
            string path = AssetPath.Normalize(relativePath);
            if (!Manifest.TryGetAsset(path, out AssetDescriptor? descriptor))
            {
                throw new FileNotFoundException("The requested asset is not declared by the archive manifest.", path);
            }

            return ValueTask.FromResult(new AssetReadSnapshot(descriptor, new MemoryStream(_contents[path], writable: false)));
        }

        private static Dictionary<string, byte[]> Scan(
            DirectoryInfo root,
            AssetDirectoryExclusions exclusions,
            CancellationToken cancellationToken,
            out AssetManifest manifest)
        {
            var descriptors = new List<AssetDescriptor>();
            var contents = new Dictionary<string, byte[]>(StringComparer.Ordinal);
            var pending = new Stack<DirectoryInfo>();
            pending.Push(root);
            while (pending.Count != 0)
            {
                cancellationToken.ThrowIfCancellationRequested();
                DirectoryInfo directory = pending.Pop();
                foreach (FileSystemInfo entry in directory.GetFileSystemInfos())
                {
                    cancellationToken.ThrowIfCancellationRequested();
                    // A default pattern leaves the entry out before it is examined, so nothing below .git is read.
                    if (entry is DirectoryInfo
                        ? exclusions.ExcludesDirectory(entry.Name)
                        : exclusions.ExcludesDefaultFileName(entry.Name))
                    {
                        continue;
                    }

                    ThrowIfLink(entry);
                    if (entry is DirectoryInfo childDirectory)
                    {
                        pending.Push(childDirectory);
                        continue;
                    }

                    if (entry is not FileInfo file)
                    {
                        throw new InvalidDataException(
                            $"Asset directory entry '{entry.FullName}' is not a regular file.");
                    }

                    string relativePath = ToAssetPath(root.FullName, file.FullName);
                    if (exclusions.ExcludesFile(relativePath, file.Name))
                    {
                        continue;
                    }

                    byte[] content = File.ReadAllBytes(file.FullName);
                    ThrowIfLink(new FileInfo(file.FullName));
                    using var stream = new MemoryStream(content, writable: false);
                    descriptors.Add(AssetHashing.Describe(
                        relativePath,
                        stream,
                        mediaType: null,
                        StringComparer.Ordinal.Equals(relativePath, exclusions.EntryPoint),
                        InferCacheMode(relativePath)));
                    contents.Add(relativePath, content);
                }
            }

            manifest = new AssetManifest(descriptors);
            return contents;
        }

        private static string ToAssetPath(string root, string path)
        {
            string relative = Path.GetRelativePath(root, path)
                .Replace(Path.DirectorySeparatorChar, '/')
                .Replace(Path.AltDirectorySeparatorChar, '/');
            return AssetPath.Normalize(relative);
        }

        private static void ThrowIfLink(FileSystemInfo entry)
        {
            if ((entry.Attributes & FileAttributes.ReparsePoint) != 0 || entry.LinkTarget is not null)
            {
                throw new InvalidDataException(
                    "Trusted generated asset output cannot contain symbolic links or reparse points.");
            }
        }
    }
}

/// <summary>A deterministic, validated description of a Runic Assets archive.</summary>
public sealed class AssetArchiveInspection
{
    private readonly string _archiveVersion;

    internal AssetArchiveInspection(AssetManifest manifest, byte[] canonicalManifest, string archiveVersion)
    {
        Manifest = manifest ?? throw new ArgumentNullException(nameof(manifest));
        ManifestSha256 = Convert.ToHexStringLower(SHA256.HashData(canonicalManifest));
        _archiveVersion = archiveVersion;
    }

    /// <summary>
    /// Gets the archive schema identifier of the canonical form: <c>runic.assets.archive/2</c> when assets share
    /// content, otherwise <see cref="AssetArchive.CurrentVersion"/>.
    /// </summary>
    public string ArchiveVersion => _archiveVersion;

    /// <summary>Gets the validated, immutable manifest owned by the archive.</summary>
    public AssetManifest Manifest { get; }

    /// <summary>Gets the SHA-256 digest of the archive's canonical manifest bytes.</summary>
    public string ManifestSha256 { get; }

    // A line-oriented report with deterministic field and asset ordering, for tests. Not a versioned format.
    internal string ToDeterministicReport()
    {
        var report = new StringBuilder();
        report.Append("archiveVersion=").Append(ArchiveVersion).Append('\n');
        report.Append("manifestVersion=").Append(Manifest.Version).Append('\n');
        report.Append("manifestSha256=").Append(ManifestSha256).Append('\n');
        report.Append("assetCount=").Append(Manifest.Assets.Count).Append('\n');
        report.Append("entryPoint=").Append(Manifest.EntryPoint.RelativePath).Append('\n');
        foreach (AssetDescriptor asset in Manifest.Assets)
        {
            report.Append("asset=")
                .Append(asset.RelativePath).Append('|')
                .Append(asset.MediaType).Append('|')
                .Append(asset.Length).Append('|')
                .Append(asset.Sha256).Append('|')
                .Append(asset.IsEntryPoint ? "entry" : "content").Append('|')
                .Append(asset.CacheMode).Append('\n');
        }

        return report.ToString();
    }
}

/// <summary>Bounds memory and file counts while reading an untrusted asset archive.</summary>
/// <remarks>
/// One asset is also bounded at 2,147,483,647 bytes (2³¹−1, <see cref="int.MaxValue"/>), the largest .NET array, a fixed
/// limit that these options do not raise: an archive with a larger asset fails to read with
/// <see cref="InvalidDataException"/>, as for these limits.
/// </remarks>
public sealed class AssetArchiveReadOptions
{
    /// <summary>The maximum compressed archive size accepted in bytes.</summary>
    public long MaxArchiveBytes { get; init; } = 1024L * 1024L * 1024L;

    /// <summary>The maximum decompressed manifest size accepted in bytes.</summary>
    public long MaxManifestBytes { get; init; } = 4L * 1024L * 1024L;

    /// <summary>The maximum number of declared files.</summary>
    public int MaxFileCount { get; init; } = 100_000;

    /// <summary>The maximum combined uncompressed content size accepted in bytes.</summary>
    public long MaxTotalUncompressedBytes { get; init; } = 1024L * 1024L * 1024L;
}

/// <summary>
/// An immutable source loaded from a Runic Assets archive. <see cref="AssetArchive.Read(Stream, AssetArchiveReadOptions?)"/>
/// and <see cref="AssetArchive.ReadAsync"/> inflate and verify every asset into memory;
/// <see cref="AssetArchive.ReadEmbedded"/> inflates each asset of an embedded archive when it is first opened.
/// </summary>
public sealed class AssetArchiveSource : IAssetSource
{
    private readonly AssetArchiveContent _content;

    internal AssetArchiveSource(AssetManifest manifest, AssetArchiveContent content)
    {
        Manifest = manifest;
        _content = content;
    }

    /// <inheritdoc />
    public AssetManifest Manifest { get; }

    /// <summary>Checks every asset against its manifest length and SHA-256 digest, inflating the ones not read yet.</summary>
    /// <param name="cancellationToken">Cancels the check between assets.</param>
    /// <exception cref="InvalidDataException">An asset does not match its descriptor.</exception>
    public ValueTask ValidateAsync(CancellationToken cancellationToken = default)
    {
        foreach (AssetDescriptor descriptor in Manifest.Assets)
        {
            cancellationToken.ThrowIfCancellationRequested();
            _content.TryGet(descriptor.RelativePath, out byte[]? content);
            using var stream = new MemoryStream(content!, writable: false);
            AssetHashing.Verify(descriptor, stream);
        }

        return ValueTask.CompletedTask;
    }

    /// <inheritdoc />
    public ValueTask<AssetReadSnapshot> OpenAsync(
        string relativePath,
        CancellationToken cancellationToken = default)
    {
        cancellationToken.ThrowIfCancellationRequested();
        string path = AssetPath.Normalize(relativePath);
        if (!Manifest.TryGetAsset(path, out AssetDescriptor? descriptor)
            || !_content.TryGet(path, out byte[]? content))
        {
            throw new FileNotFoundException("The requested asset is not declared by the archive manifest.", path);
        }

        return ValueTask.FromResult(new AssetReadSnapshot(
            descriptor,
            new MemoryStream(content, writable: false)));
    }
}

// The assets of an AssetArchiveSource by path: inflated up front, or inflated from the archive's ZIP entries on first
// use and kept. ZipArchive reads its entries through one shared stream, so inflation is serialized.
internal sealed class AssetArchiveContent
{
    private readonly Dictionary<string, Slot> _slots;
    private readonly Lock _gate = new();

    // Content inflated on first use from the archive's entries. An asset with contentPath shares the slot of the asset
    // it names, so shared content is inflated and kept once.
    internal AssetArchiveContent(AssetDescriptor[] descriptors, ArchiveEntryData?[] entries, string?[] contentPaths)
    {
        _slots = new Dictionary<string, Slot>(descriptors.Length, StringComparer.Ordinal);
        for (int index = 0; index < descriptors.Length; index++)
        {
            if (entries[index] is ArchiveEntryData entry)
            {
                _slots.Add(descriptors[index].RelativePath, new Slot(descriptors[index], entry));
            }
        }

        for (int index = 0; index < descriptors.Length; index++)
        {
            // The named asset must have its own entry (so no asset with contentPath, and not itself) and the same length.
            if (contentPaths[index] is string contentPath)
            {
                if (!_slots.TryGetValue(contentPath, out Slot? slot)
                    || slot.Descriptor.RelativePath != contentPath
                    || slot.Descriptor.Length != descriptors[index].Length)
                {
                    throw new InvalidDataException(
                        "An asset's contentPath does not name a stored asset of the same length in the asset archive.");
                }

                _slots.Add(descriptors[index].RelativePath, slot);
            }
        }
    }

    internal bool TryGet(string path, [System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out byte[]? content)
    {
        if (!_slots.TryGetValue(path, out Slot? slot))
        {
            content = null;
            return false;
        }

        content = Volatile.Read(ref slot.Content);
        if (content is null)
        {
            lock (_gate)
            {
                content = slot.Content;
                if (content is null)
                {
                    content = AssetArchive.Inflate(slot.Entry!, slot.Descriptor.Length, $"Asset '{slot.Descriptor.RelativePath}'");
                    Volatile.Write(ref slot.Content, content);
                    slot.Entry = null;
                }
            }
        }

        return true;
    }

    private sealed class Slot(AssetDescriptor descriptor, ArchiveEntryData? entry)
    {
        internal readonly AssetDescriptor Descriptor = descriptor;
        // Cleared once inflated, so the slot no longer keeps the archive's buffer alive.
        internal ArchiveEntryData? Entry = entry;
        internal byte[]? Content;
    }
}
