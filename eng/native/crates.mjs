// The crates of the native Desktop server (native/Cargo.lock):
//
//   node eng/native/crates.mjs notices   writes native/THIRD-PARTY-NOTICES.md from `cargo metadata`
//   node eng/native/crates.mjs check     fails on a crate whose license is not allowed, a stale notices file, or (with
//                                        --release-age, which needs crates.io) a version published within the last day
//
// The one-day rule is D038's rule for third-party npm and NuGet versions, applied to crates.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const manifest = resolve(root, "native/Cargo.toml");
const noticesPath = resolve(root, "native/THIRD-PARTY-NOTICES.md");
// SPDX identifiers whose terms allow redistribution in an MIT package without source disclosure.
const allowed = new Set(["MIT", "Apache-2.0", "Apache-2.0 WITH LLVM-exception", "BSD-2-Clause", "BSD-3-Clause",
  "ISC", "Zlib", "Unicode-3.0", "Unicode-DFS-2016", "0BSD", "CC0-1.0", "Unlicense", "BSL-1.0"]);

function shipped() {
  // The library's own dependency graph, without dev-dependencies, for every target.
  const metadata = JSON.parse(execFileSync("cargo", ["metadata", "--format-version", "1", "--locked",
    "--manifest-path", manifest], { encoding: "utf8", maxBuffer: 64 << 20 }));
  const byId = new Map(metadata.packages.map(item => [item.id, item]));
  const nodes = new Map(metadata.resolve.nodes.map(node => [node.id, node]));
  const root = metadata.packages.find(item => item.name === "runic-server");
  const seen = new Set();
  const visit = id => {
    if (seen.has(id)) return;
    seen.add(id);
    for (const dependency of nodes.get(id).deps)
      if (dependency.dep_kinds.some(kind => kind.kind === null || kind.kind === "build")) visit(dependency.pkg);
  };
  visit(root.id);
  return [...seen].map(id => byId.get(id)).filter(item => item.source?.startsWith("registry+"))
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

// "MIT OR Apache-2.0" passes when one alternative is allowed; "A AND B" needs both.
// Older crates write "MIT/Apache-2.0" for OR.
const licensed = expression => expression.split(/\s+OR\s+|\//).some(choice =>
  choice.replace(/[()]/g, "").split(/\s+AND\s+/).every(term => allowed.has(term.trim())));

function notices(crates) {
  const rows = crates.map(item =>
    `| ${item.name} | ${item.version} | ${item.license ?? "(none)"} | ${item.repository ?? ""} |`);
  return `# Third-party notices

The native server library of Runic.Desktop.NativeServer (native/runic-server) statically links these crates from
crates.io. Generated by \`node eng/native/crates.mjs notices\` from native/Cargo.lock; the license texts are in each
crate's source package and repository.

| Crate | Version | License | Repository |
| --- | --- | --- | --- |
${rows.join("\n")}

The library also contains the Rust standard library (MIT OR Apache-2.0, https://github.com/rust-lang/rust).
`;
}

async function releaseAge(crates) {
  const young = [];
  const now = Date.now();
  for (const item of crates) {
    const response = await fetch(`https://crates.io/api/v1/crates/${item.name}/${item.version}`,
      { headers: { "User-Agent": "runic-sdk release-age check (https://github.com/Runic-Artifex/runic-sdk)" } });
    if (!response.ok) throw new Error(`crates.io answered ${response.status} for ${item.name} ${item.version}`);
    const created = Date.parse((await response.json()).version.created_at);
    if (now - created < 24 * 60 * 60 * 1000) young.push(`${item.name} ${item.version} (${new Date(created).toISOString()})`);
  }
  return young;
}

const [command, ...options] = process.argv.slice(2);
const crates = shipped();
if (command === "notices") {
  writeFileSync(noticesPath, notices(crates));
  console.log(`${crates.length} crates written to native/THIRD-PARTY-NOTICES.md`);
} else if (command === "check") {
  const problems = crates.filter(item => !item.license || !licensed(item.license))
    .map(item => `${item.name} ${item.version}: license ${item.license ?? "(none)"} is not allowed`);
  if (readFileSync(noticesPath, "utf8") !== notices(crates))
    problems.push("native/THIRD-PARTY-NOTICES.md is stale: run node eng/native/crates.mjs notices");
  if (options.includes("--release-age"))
    for (const crate of await releaseAge(crates)) problems.push(`${crate} was published within the last day (D038)`);
  if (problems.length) {
    console.error(problems.join("\n"));
    process.exit(1);
  }
  console.log(`${crates.length} crates: licenses allowed, notices current${options.includes("--release-age") ? ", none published within a day" : ""}.`);
} else {
  console.error("usage: node eng/native/crates.mjs notices|check [--release-age]");
  process.exit(2);
}
