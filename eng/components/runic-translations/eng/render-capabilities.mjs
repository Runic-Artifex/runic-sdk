import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const matrixPath = resolve(root, "spec/capabilities-v1.json");
const documentationPath = resolve(root, "docs/capabilities.md");
const check = process.argv.slice(2).includes("--check");
const matrix = JSON.parse(await readFile(matrixPath, "utf8"));

const mark = value => value ? "yes" : "—";
const lines = [
  "# Locale and formatter capabilities",
  "",
  "> Generated from `spec/capabilities-v1.json`; do not edit this file directly.",
  "",
  `Capability matrix version: **${matrix.capabilityMatrixVersion}**  `,
  `Release target: **${matrix.releaseTarget}**  `,
  `CLDR source: **${matrix.cldr.version}** (JSON tag \`${matrix.cldr.jsonTag}\`, ${matrix.cldr.license})  `,
  `Conforming backends: **${matrix.backends.join(", ")}**`,
  "",
  "## Locale selectors and relative time",
  "",
  "| Locale family | Cardinal | Ordinal | Relative time |",
  "|---|---:|---:|---:|",
  ...matrix.locales.map(locale => `| \`${locale.tag}\` | ${mark(locale.cardinal)} | ${mark(locale.ordinal)} | ${mark(locale.relativeTime)} |`),
  "",
  "Locale variants such as `de-DE` use the declared base language capability.",
  "Unsupported selector or relative-time combinations fail compilation with `RTR0031`.",
  `Cardinal selector equivalence: **${matrix.messageProfile.cardinal}**.`,
  `Ordinal selector equivalence: **${matrix.messageProfile.ordinal}**.`,
  `Relative-time equivalence: **${matrix.messageProfile.relativeTime}**.`,
  "Plural selection and relative-time language patterns are generated from the pinned CLDR subset; the ESM backend does not delegate them to host `Intl` data.",
  "",
  "## Formatter equivalence",
  "",
  "| Formatter | Forms | Equivalence |",
  "|---|---|---|",
];

for (const [formatter, forms] of Object.entries(matrix.formatterProfile)) {
  const grouped = new Map();
  for (const [form, equivalence] of Object.entries(forms)) {
    const names = grouped.get(equivalence) ?? [];
    names.push(form);
    grouped.set(equivalence, names);
  }
  for (const [equivalence, names] of grouped)
    lines.push(`| \`${formatter}\` | ${names.map(name => `\`${name}\``).join(", ")} | ${equivalence} |`);
}

lines.push(
  "",
  `**Exact:** ${matrix.equivalence.exact}`,
  "",
  `**Semantic:** ${matrix.equivalence.semantic}`,
  "",
  "The first public preview deliberately claims only the locale families above.",
  "A platform may recognize other BCP 47 tags for scalar formatting, but they are",
  "not part of the cross-runtime support promise until they appear in the matrix",
  "and shared .NET/ESM conformance fixtures.",
  "",
);

const rendered = lines.join("\n");
if (check) {
  const existing = await readFile(documentationPath, "utf8");
  if (existing !== rendered) {
    console.error("docs/capabilities.md is stale; run node eng/render-capabilities.mjs");
    process.exitCode = 1;
  }
} else {
  await writeFile(documentationPath, rendered, "utf8");
}
