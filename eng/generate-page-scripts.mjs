// Generates packages/dotnet/Runic.Desktop/Internal/PageScripts.g.cs: the page scripts Runic.Desktop injects or serves, as
// UTF-8 literals (runic-sdk#1109). A u8 literal is data that the trimmer and NativeAOT keep only with the code that
// reads it, so a Windows build has no macOS or WebKitGTK script, unlike a manifest resource; and UTF-8 takes half the
// bytes of a UTF-16 string literal.
//
// - WebUiBridge.js, the page script of /webui.js, is minified: esbuild removes comments, indentation and line breaks and
//   nothing else. Names and statements stay, so the script reads in DevTools and each declaration keeps its form
//   (const TOKEN=…;). The placeholders that WebUiWindow.BuildBridgeScript replaces (__TOKEN__, __PORT__, …) are global
//   names or string contents, which esbuild keeps.
// - MacOsWindowChrome.js and WebKitGtkKeyboard.js are embedded as they are; browser tests load the same files.
//
// Run it after changing one of the scripts; --check fails when the committed file is not its output
// (tests/engineering/page-scripts.test.mjs runs the same check).
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { transform } from "esbuild";

const root = resolve(import.meta.dirname, "..");
const internal = resolve(root, "packages/dotnet/Runic.Desktop/Internal");
export const bridgeSource = resolve(internal, "WebUiBridge.js");
export const generated = resolve(internal, "PageScripts.g.cs");

export async function minifyBridge(text = readFileSync(bridgeSource, "utf8")) {
  const result = await transform(text, { loader: "js", minifyWhitespace: true, legalComments: "none", charset: "utf8" });
  return result.code;
}

// The scripts as PageScripts.g.cs declares them: property name, source file and the text it holds.
export async function scripts() {
  const read = name => readFileSync(resolve(internal, name), "utf8");
  return [
    { name: "WebUiBridge", file: "WebUiBridge.js", text: await minifyBridge(read("WebUiBridge.js")), minified: true },
    { name: "MacOsWindowChrome", file: "MacOsWindowChrome.js", text: read("MacOsWindowChrome.js") },
    { name: "WebKitGtkKeyboard", file: "WebKitGtkKeyboard.js", text: read("WebKitGtkKeyboard.js") },
  ];
}

export async function render() {
  const lines = [
    "// <auto-generated>",
    "// Generated by eng/generate-page-scripts.mjs from WebUiBridge.js (minified), MacOsWindowChrome.js and",
    "// WebKitGtkKeyboard.js. Do not edit: change the script and run bun eng/generate-page-scripts.mjs.",
    "// </auto-generated>",
    "namespace Runic.Desktop.Internal;",
    "",
    "internal static class PageScripts",
    "{",
  ];
  for (const script of await scripts()) {
    if (script.text.includes('""""')) throw new Error(`${script.file} contains """", which ends the literal.`);
    // A raw literal's value excludes the line break before its closing quotes, so the text keeps a trailing newline.
    lines.push(`    // ${script.file}${script.minified ? ", minified" : ""}.`);
    lines.push(`    internal static ReadOnlySpan<byte> ${script.name} => """"`);
    lines.push(`${script.text}`);
    lines.push(`""""u8;`);
    lines.push("");
  }
  lines[lines.length - 1] = "}";
  return lines.join("\n") + "\n";
}

if (import.meta.main) {
  const code = await render();
  if (process.argv.includes("--check")) {
    if (readFileSync(generated, "utf8") !== code) {
      console.error(`${generated} is out of date; run bun eng/generate-page-scripts.mjs.`);
      process.exit(1);
    }
  } else {
    writeFileSync(generated, code);
  }
}
