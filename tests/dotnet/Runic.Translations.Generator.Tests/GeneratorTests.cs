    private static void TomlMembershipChanges()
    {
        string project = Project.Replace("\"schemaVersion\": 1,", "\"schemaVersion\": 1, \"sourceLayout\": \"locale-toml\",", StringComparison.Ordinal)
            .Replace(",\n  \"locales\": [ \"en\" ]", string.Empty, StringComparison.Ordinal);
        var english = new TestInput("C:/repo/translations/en.toml", "Toml", "Greeting = 'Hello'\n");
        var german = new TestInput("C:/repo/translations/de.toml", "Toml", "Greeting = 'Hallo'\n");
        GeneratorRun initial = GeneratorTestHost.Run(ProjectInput(project), english);
        GeneratorRunResult added = GeneratorTestHost.Rerun(initial, ProjectInput(project), english, german);
        Assert.Equal(0, added.Diagnostics.Length, string.Join("\n", added.Diagnostics));
        Assert.True(string.Join("\n", added.GeneratedSources.Select(static source => source.SourceText.ToString())).Contains("Hallo", StringComparison.Ordinal), "added locale was ignored");
        GeneratorRun withGerman = GeneratorTestHost.Run(ProjectInput(project), english, german);
        GeneratorRunResult removed = GeneratorTestHost.Rerun(withGerman, ProjectInput(project), english);
        Assert.Equal(0, removed.Diagnostics.Length, string.Join("\n", removed.Diagnostics));
        Assert.True(!string.Join("\n", removed.GeneratedSources.Select(static source => source.SourceText.ToString())).Contains("Hallo", StringComparison.Ordinal), "removed locale survived");
    }

