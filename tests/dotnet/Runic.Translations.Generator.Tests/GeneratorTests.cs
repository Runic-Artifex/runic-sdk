                    var text = new AppText(manager);
                    string typed = text.{{member}}("dash", "accent", "keyword", "unicode");
                    global::Runic.Translations.TextArgument[] arguments =
                    [
                        global::Runic.Translations.TextArgument.CreateRmf2("a-b", new global::Runic.Translations.TextArgument("_", "dash")),
                        global::Runic.Translations.TextArgument.CreateRmf2("café", new global::Runic.Translations.TextArgument("_", "accent")),
                        global::Runic.Translations.TextArgument.CreateRmf2("class", new global::Runic.Translations.TextArgument("_", "keyword")),
                        global::Runic.Translations.TextArgument.CreateRmf2("用户", new global::Runic.Translations.TextArgument("_", "unicode")),
