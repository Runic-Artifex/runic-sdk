    private static void Rmf2V5GenerationCompiles()
    {
        string project = Project.Replace("\"schemaVersion\": 1,", "\"schemaVersion\": 1, \"sourceLayout\": \"rmf2-v1\",", StringComparison.Ordinal);
        GeneratorRun shipping = GeneratorTestHost.Run(ProjectInput(project),
            new TestInput("C:/repo/translations/en.rmf2", "Rmf2", "literal = {1e+2 :number}"));
        Assert.True(shipping.SingleResult.Diagnostics.Any(static diagnostic => diagnostic.Id == "RTR0065"),
            "the shipping generator silently activated the staged v5 profile");
        Assert.Equal(0, shipping.SingleResult.GeneratedSources.Length, "shipping generator emitted v5-only input");
        const string resource = """
            account {
              summary =
                .input {$count :integer}
                .input {$rate :number}
                .local $percent = {$rate :number style=percent maximumFractionDigits=2}
                .match $count
                one {{One item at {$percent}}}
                * {{{$count} items at {$percent}}}
              rich = {#strong @open}Hello{/strong @close}
              carriers =
                .input {$boolean :runic:boolean}
                .input {$date :date}
                .input {$datetime :datetime}
                .input {$guid :runic:uuid}
                .input {$time :time}
                {{{$boolean} {$date} {$datetime} {$guid} {$time}}}
            }
            """;
        GeneratorRun run = GeneratorTestHost.RunRmf2V5(ProjectInput(project),
            new TestInput("C:/repo/translations/en.rmf2", "Rmf2", resource));
        Assert.Equal(0, run.SingleResult.Diagnostics.Length, string.Join("\n", run.SingleResult.Diagnostics));
        Assert.Equal(4, run.SingleResult.GeneratedSources.Length, "v5 generated concerns");
        string text = Serialize(run);
        Diagnostic[] errors = run.Compilation.GetDiagnostics().Where(static diagnostic => diagnostic.Severity == DiagnosticSeverity.Error).ToArray();
        Assert.Equal(0, errors.Length, string.Join("\n", errors.Select(static error => error.ToString())) + "\n" + text);
        Assert.True(text.Contains("CompiledTranslationDefinition.FromRmf2Inputs", StringComparison.Ordinal), "v5 definition factory missing");
        Assert.True(text.Contains("CompiledTextMessage.FromRmf2", StringComparison.Ordinal), "v5 message wrapper missing");
        Assert.True(text.Contains("new global::Runic.Translations.CompiledRmf2Message", StringComparison.Ordinal), "typed v5 model missing");
        Assert.True(text.Contains("EnsureRmf2RuntimeAbi(2)", StringComparison.Ordinal), "literal ABI 2 guard missing");
        Assert.True(text.Contains("public const int Rmf2RuntimeAbiVersion = 2;", StringComparison.Ordinal), "literal ABI 2 marker missing");
        Assert.Equal(text, Serialize(GeneratorTestHost.RunRmf2V5(
            new TestInput("C:/repo/translations/en.rmf2", "Rmf2", resource), ProjectInput(project))),
            "v5 generated bytes depend on input enumeration");
    }

