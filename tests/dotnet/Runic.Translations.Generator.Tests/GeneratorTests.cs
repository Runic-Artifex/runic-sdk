            Execute(run, "Example.Localization.V5NameProbe", "Run"), "typed and span caller identity");
        string generated = Serialize(run);
        foreach (string name in new[] { "a-b", "café", "class", "用户" })
        {
            Assert.True(generated.Contains("TextArgument.CreateRmf2(" + Quote(name), StringComparison.Ordinal), "wire identity missing: " + name);
            Assert.True(generated.Contains(Encoded(name), StringComparison.Ordinal), "encoded parameter missing: " + name);
        }
        Assert.True(Encoded("a-b") != Encoded("a_b"), "punctuation mapping collided");
        Assert.True(Encoded("café") == Encoded("cafe\u0301"), "NFC equivalents did not converge");
        Assert.True(Encoded("1lead").All(static character => char.IsAsciiLetterOrDigit(character) || character == '_'), "leading-digit mapping is not a C# identifier");
        Assert.True(Encoded("+-.") != Encoded("_"), "punctuation mapping collided");
    }

