                    return typed + "|" + fallback;
                }
            }
            """;
        GeneratorRun run = GeneratorTestHost.RunRmf2V5WithConsumer(source, ProjectInput(project),
            new TestInput("C:/repo/translations/en.rmf2", "Rmf2", resource));
