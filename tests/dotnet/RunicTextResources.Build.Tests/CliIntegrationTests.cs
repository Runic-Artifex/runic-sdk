    private static void ResponseFileAcceptsManyDocuments()
    {
        using TemporaryDirectory temporary = new();
        const int documentCount = 96;
        File.WriteAllText(
            temporary.Resolve("manifest.json"),
            "{\"schemaVersion\":1,\"catalog\":\"many\",\"code\":{\"namespace\":\"RunicTextResources.Examples.Localization\",\"className\":\"ManyText\"},\"defaultLocale\":\"en\",\"locales\":[{\"tag\":\"en\"}],\"layers\":[{\"name\":\"base\",\"priority\":0}]}",
            new UTF8Encoding(false));
        var response = new StringBuilder()
            .AppendLine("validate")
            .AppendLine("--catalog")
            .AppendLine(CultureInfo.InvariantCulture, $"\"{temporary.Resolve("manifest.json")}\"")
            .AppendLine("--documents");
        for (int index = 0; index < documentCount; index++)
        {
            string path = temporary.Resolve($"document-{index:D3}.json");
            File.WriteAllText(
                path,
                $"{{\"schemaVersion\":1,\"catalog\":\"many\",\"locale\":\"en\",\"layer\":\"base\",\"resources\":{{\"Key{index:D3}\":\"Value {index}\"}}}}",
                new UTF8Encoding(false));
            response.AppendLine(CultureInfo.InvariantCulture, $"\"{path}\"");
        }

        string responsePath = temporary.Resolve("many-documents.rsp");
        File.WriteAllText(responsePath, response.ToString(), new UTF8Encoding(false));
        ProcessResult result = TestFixture.RunTool(temporary, $"@{responsePath}");
        Assert.Equal(0, result.ExitCode, result.Combined);
        Assert.Contains($"{documentCount} document(s)", result.StandardOutput);
    }

    private static void LocaleExtrasStayDataOnly()
    {
        using TemporaryDirectory temporary = new();
        WriteExtraFixture(temporary, includeExtra: true);
        ProcessResult withExtra = TestFixture.RunTool(
            temporary,
            "generate",
            "--catalog",
            "manifest.json",
            "--documents",
            "en.json",
            "fr.json",
            "--output",
            "with-extra",
            "--emit-csharp");
        Assert.Equal(0, withExtra.ExitCode, withExtra.Combined);

        string data = File.ReadAllText(temporary.Resolve("with-extra", "ExtraText.CatalogData.g.cs"), Encoding.UTF8);
        int canonical = data.IndexOf("CompiledTextResourceDefinition(\"A\"", StringComparison.Ordinal);
        int extra = data.IndexOf("CompiledTextResourceDefinition(\"Extra.Z\"", StringComparison.Ordinal);
        Assert.True(canonical >= 0 && extra > canonical, "Canonical ID 0 was not followed by the data-only extra ID 1.");
        Assert.Contains("}, isCanonical: true)", data[canonical..extra]);
        Assert.Contains("}, isCanonical: false)", data[extra..]);
        string keys = File.ReadAllText(temporary.Resolve("with-extra", "ExtraText.Keys.g.cs"), Encoding.UTF8);
        string accessors = File.ReadAllText(temporary.Resolve("with-extra", "ExtraText.Accessors.g.cs"), Encoding.UTF8);
        Assert.False(keys.Contains("\"Extra.Z\"", StringComparison.Ordinal), "Locale-only key leaked into generated keys.");
        Assert.False(accessors.Contains("ExtraGroup", StringComparison.Ordinal), "Locale-only key leaked into generated accessors.");

        WriteExtraFixture(temporary, includeExtra: false);
        ProcessResult withoutExtra = TestFixture.RunTool(
            temporary,
            "generate",
            "--catalog",
            "manifest.json",
            "--documents",
            "en.json",
            "fr.json",
            "--output",
            "without-extra",
            "--emit-csharp");
        Assert.Equal(0, withoutExtra.ExitCode, withoutExtra.Combined);
        string firstRegistration = File.ReadAllText(temporary.Resolve("with-extra", "ExtraText.Registration.g.cs"), Encoding.UTF8);
        string secondRegistration = File.ReadAllText(temporary.Resolve("without-extra", "ExtraText.Registration.g.cs"), Encoding.UTF8);
        Assert.Equal(ReadFingerprint(firstRegistration), ReadFingerprint(secondRegistration), "Allowed locale extras changed the canonical fingerprint");
    }

    private static void WriteExtraFixture(TemporaryDirectory temporary, bool includeExtra)
    {
        const string manifest = """
            {"schemaVersion":1,"catalog":"extra","code":{"namespace":"RunicTextResources.Examples.Localization","className":"ExtraText"},"defaultLocale":"en","locales":[{"tag":"en"},{"tag":"fr","fallback":"en"}],"layers":[{"name":"base","priority":0}],"validation":{"translationCompleteness":"allow","extraLocaleKeys":"allow"}}
            """;
        string french = includeExtra
            ? "{\"schemaVersion\":1,\"catalog\":\"extra\",\"locale\":\"fr\",\"layer\":\"base\",\"resources\":{\"A\":\"Une\",\"Extra\":{\"Z\":\"Supplément\"}}}"
            : "{\"schemaVersion\":1,\"catalog\":\"extra\",\"locale\":\"fr\",\"layer\":\"base\",\"resources\":{\"A\":\"Une\"}}";
        File.WriteAllText(temporary.Resolve("manifest.json"), manifest, new UTF8Encoding(false));
        File.WriteAllText(temporary.Resolve("en.json"), "{\"schemaVersion\":1,\"catalog\":\"extra\",\"locale\":\"en\",\"layer\":\"base\",\"resources\":{\"A\":\"A\"}}", new UTF8Encoding(false));
        File.WriteAllText(temporary.Resolve("fr.json"), french, new UTF8Encoding(false));
    }

    private static string ReadFingerprint(string registration)
    {
        const string marker = "ContractFingerprint = \"";
        int start = registration.IndexOf(marker, StringComparison.Ordinal);
        Assert.True(start >= 0, "Generated registration omitted ContractFingerprint.");
        start += marker.Length;
        int end = registration.IndexOf('"', start);
        return registration[start..end];
    }

