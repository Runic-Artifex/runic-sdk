    private static void PortableDestinationAliasesAreRejected()
    {
        Assembly tool = Assembly.LoadFrom(RepositoryPaths.ToolAssembly);
        Type artifactType = tool.GetType("RunicTextResources.Tool.ToolArtifact", throwOnError: true)!;
        Type filesType = tool.GetType("RunicTextResources.Tool.ArtifactFiles", throwOnError: true)!;
        object first = Activator.CreateInstance(
            artifactType,
            BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic,
            binder: null,
            args: ["Case.txt", new byte[] { 1 }],
            culture: null)!;
        object second = Activator.CreateInstance(
            artifactType,
            BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic,
            binder: null,
            args: ["case.txt", new byte[] { 2 }],
            culture: null)!;
        Type listType = typeof(List<>).MakeGenericType(artifactType);
        object list = Activator.CreateInstance(listType)!;
        listType.GetMethod("Add")!.Invoke(list, [first]);
        listType.GetMethod("Add")!.Invoke(list, [second]);
        MethodInfo normalize = filesType.GetMethod("Normalize", BindingFlags.Static | BindingFlags.NonPublic)!;
        try
        {
            _ = normalize.Invoke(null, [list]);
            throw new InvalidOperationException("Portable case-alias collision was accepted.");
        }
        catch (TargetInvocationException exception)
        {
            Assert.Contains("RTR0020", exception.InnerException?.Message ?? string.Empty);
            Assert.Contains("collision", exception.InnerException?.Message ?? string.Empty);
        }
    }

