    private static void GenerateWritesArtifactSet()
    {
        using TemporaryDirectory temporary = new();
        TestFixture.CopyMinimal(temporary);
        ProcessResult result = TestFixture.Generate(temporary);

        Assert.Equal(0, result.ExitCode, result.Combined);
        Assert.Equal(string.Join('|', MinimalArtifacts), string.Join('|', TestFixture.RelativeFiles(temporary.Resolve("generated"))));
        foreach (string path in MinimalArtifacts)
        {
            byte[] bytes = File.ReadAllBytes(temporary.Resolve("generated", path));
            Assert.False(bytes.Length >= 3 && bytes[0] == 0xef && bytes[1] == 0xbb && bytes[2] == 0xbf, $"{path} has a UTF-8 BOM.");
            if (path.EndsWith(".json", StringComparison.Ordinal))
            {
                Assert.True(bytes.Length > 0 && bytes[^1] != (byte)'\n', $"{path} has a forbidden terminal newline.");
            }
            else
            {
                Assert.True(bytes.Length > 0 && bytes[^1] == (byte)'\n', $"{path} lacks a final LF.");
            }
        }
    }

