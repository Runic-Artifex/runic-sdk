// Library mode (#1318, RunicApplicationFrontendClientLibrary=true, --client-library): the generated clients become a
// module that other frontends import, through the runic-clients.ts and runic-mocks.ts barrels, and the assembly carries
// the library-mode marker.
internal sealed partial class CodegenDiagnosticsTests
{
    [Test]
    public async Task ClientLibraryWritesTheBarrelsContractsAndMarkerAsync()
    {
        var root = FindWorkspaceRoot();
        var configuration = System.Reflection.CustomAttributeExtensions.GetCustomAttribute<System.Reflection.AssemblyConfigurationAttribute>(
            typeof(CodegenDiagnosticsTests).Assembly)?.Configuration ?? "Release";
        var generator = Path.Combine(root, "tools", "Runic.Application.Views.Codegen", "bin", configuration, "net10.0", "BridgeCodegen.dll");
        var temporaryRoot = Path.Combine(Path.GetTempPath(), $"runic-codegen-client-library-{Guid.NewGuid():N}");
        try
        {
            const string Library = Preamble + """
                public sealed record LicenseEntry(string Name, string Text);
                [RunicSharedClient]
                public interface ITitled
                {
                    string Title { get; }
                }
                public sealed class AboutDialogViewModel : FixtureModel, ITitled
                {
                    public string Title => "";
                    public IReadOnlyList<LicenseEntry> Licenses { get; } = [];
                }
                public sealed class SupportMenuViewModel : FixtureModel, ITitled
                {
                    public string Title => "";
                    public IRelayCommand OpenCommand { get; } = new RelayCommand(() => { });
                }
                public sealed partial class AboutDialogView : RunicView<AboutDialogViewModel>;
                [RunicViewContract("Compact")]
                public sealed partial class AboutDialogCompactView : RunicView<AboutDialogViewModel>;
                public sealed partial class SupportMenuView : RunicView<SupportMenuViewModel>;
                """;
            var csharp = await GenerateValidAsync(generator, temporaryRoot, "ClientLibrary", Library, "--client-library", "--optional")
                .ConfigureAwait(false);
            var typescript = Path.Combine(Path.GetDirectoryName(csharp)!, "ts");
            string Contract(string module)
            {
                var match = Regex.Match(File.ReadAllText(Path.Combine(typescript, module + ".ts")), "const _*bridgeContract = \"([^\"]+)\";");
                Require(match.Success, $"{module}.ts embeds no contract.");
                return match.Groups[1].Value;
            }
            var about = Contract("aboutDialog");
            var support = Contract("supportMenu");
            Require(about.StartsWith("Fixture.AboutDialogViewModel:", StringComparison.Ordinal)
                    && support.StartsWith("Fixture.SupportMenuViewModel:", StringComparison.Ordinal),
                $"Unexpected client contracts {about} and {support}.");
            var clients = File.ReadAllText(Path.Combine(typescript, "runic-clients.ts"));
            Require(clients == $$"""
                // <auto-generated />
                // The generated clients of this library (RunicApplicationFrontendClientLibrary), for applications and
                // components that import them. The mocks are in runic-mocks.ts.
                export * from "./aboutDialog.js";
                export * from "./supportMenu.js";
                export * from "./titled.js";
                export * from "./types.js";

                /**
                 * The contract of each generated client: its ViewModel and the fingerprint of the ViewModel's Bridge contract,
                 * computed from the assembly this module was generated from.
                 */
                export const runicClientContracts = {
                  aboutDialog: "{{about}}",
                  supportMenu: "{{support}}",
                } as const;

                """, $"runic-clients.ts is not the barrel of the clients, the shared client and the named types.\n{clients}");
            var mocks = File.ReadAllText(Path.Combine(typescript, "runic-mocks.ts"));
            Require(mocks == """
                // <auto-generated />
                // The generated mocks of this library's clients (RunicApplicationFrontendClientLibrary), for tests and
                // previews. Production code imports runic-clients.ts.
                export * from "./aboutDialog.mock.js";
                export * from "./supportMenu.mock.js";

                """, $"runic-mocks.ts is not the barrel of the mocks.\n{mocks}");
            var marker = File.ReadAllText(Path.Combine(csharp, "RunicClientLibrary.g.cs"));
            Require(marker.StartsWith("// <auto-generated />\n", StringComparison.Ordinal)
                    && marker.Contains("[assembly: global::System.Reflection.AssemblyMetadata(\"Runic.Application.Views.ClientLibrary\", \"1\")]", StringComparison.Ordinal),
                $"RunicClientLibrary.g.cs is not the library-mode marker.\n{marker}");
            // The marker compiles into the assembly's metadata.
            var compiled = Compile("ClientLibraryMarker", marker);
            var errors = compiled.GetDiagnostics().Where(diagnostic => diagnostic.Severity == Microsoft.CodeAnalysis.DiagnosticSeverity.Error).ToArray();
            Require(errors.Length == 0 && compiled.Assembly.GetAttributes().Any(attribute =>
                    attribute.AttributeClass?.ToDisplayString() == "System.Reflection.AssemblyMetadataAttribute"
                    && attribute.ConstructorArguments.Select(argument => argument.Value as string)
                        .SequenceEqual(["Runic.Application.Views.ClientLibrary", "1"])),
                $"The library-mode marker does not compile to the assembly metadata.\n{string.Join('\n', errors)}");

            // Without --client-library the barrels and the marker are stale output and are deleted.
            await GenerateValidAsync(generator, temporaryRoot, "ClientLibrary", Library, "--optional").ConfigureAwait(false);
            Require(!File.Exists(Path.Combine(typescript, "runic-clients.ts")) && !File.Exists(Path.Combine(typescript, "runic-mocks.ts"))
                    && !File.Exists(Path.Combine(csharp, "RunicClientLibrary.g.cs")) && File.Exists(Path.Combine(typescript, "aboutDialog.ts")),
                "Generation without --client-library kept the library's barrels or marker.");
            Require(Contract("aboutDialog") == about, "The client's contract depends on library mode.");

            // A library without named types exports no types.js.
            var plainCsharp = await GenerateValidAsync(generator, temporaryRoot, "ClientLibraryPlain", Preamble + """
                public sealed class PlainViewModel : FixtureModel
                {
                    public string Title => "";
                }
                public sealed partial class PlainView : RunicView<PlainViewModel>;
                """, "--client-library").ConfigureAwait(false);
            var plain = File.ReadAllText(Path.Combine(Path.GetDirectoryName(plainCsharp)!, "ts", "runic-clients.ts"));
            Require(plain.Contains("export * from \"./plain.js\";\n\n", StringComparison.Ordinal) && !plain.Contains("types.js", StringComparison.Ordinal)
                    && !File.Exists(Path.Combine(Path.GetDirectoryName(plainCsharp)!, "ts", "types.ts")),
                $"A library without named types exports types.js.\n{plain}");

            // A client library requires its Views, even when the generation would otherwise be optional.
            var (exitCode, output, _) = await RunGeneratorAsync(generator, temporaryRoot, "ClientLibraryNoViews",
                Preamble + "public sealed class PlainService { public int Value => 1; }", "--client-library", "--optional").ConfigureAwait(false);
            Require(exitCode != 0 && output.Contains("error RUNICBRIDGE006:", StringComparison.Ordinal)
                    && output.Contains("no Runic Window/View classes found, but Bridge generation is required here.", StringComparison.Ordinal),
                $"A client library without Views was not RUNICBRIDGE006.\n{output}");
        }
        finally
        {
            if (Directory.Exists(temporaryRoot)) Directory.Delete(temporaryRoot, recursive: true);
        }
    }
}

// Application mode (#1318, RunicApplicationFrontendClientModule, --client-module A=S): an application adds the Views of a
// referenced client library and writes their Bridges, but imports the library's generated TypeScript from S.
internal sealed partial class CodegenDiagnosticsTests
{
    private const string SharedUiSpecifier = "@fixture/shared-ui/generated";

    // A client library's source: its own namespace and base class, and with the library-mode marker that
    // RunicClientLibrary.g.cs compiles into it.
    private static string ClientLibrarySource(string ns, string body, bool marked = true) => $$"""
        using System;
        using System.Collections.Generic;
        using System.ComponentModel;
        using CommunityToolkit.Mvvm.Input;
        using Runic.Application.Views;
        {{(marked ? "[assembly: System.Reflection.AssemblyMetadata(\"Runic.Application.Views.ClientLibrary\", \"1\")]" : "")}}

        namespace {{ns}};

        public abstract class SharedModel : INotifyPropertyChanged
        {
            public event PropertyChangedEventHandler? PropertyChanged { add { } remove { } }
        }

        """ + body;

    private const string SharedUiViewModels = """
        public sealed record LicenseEntry(string Name, string Text);
        public enum Channel { Stable, Preview }
        [RunicSharedClient]
        public interface ITitled
        {
            string Title { get; }
        }
        public sealed class AboutDialogViewModel : SharedModel, ITitled
        {
            public string Title => "";
            public IReadOnlyList<LicenseEntry> Licenses { get; } = [];
            public IRelayCommand CloseCommand { get; } = new RelayCommand(() => { });
        }
        public sealed class SupportMenuViewModel : SharedModel, ITitled
        {
            public string Title => "";
            public Channel Channel { get; set; }
            public AboutDialogViewModel? About { get; }
        }

        """;

    private const string SharedUiViews = """
        public sealed partial class AboutDialogView : RunicView<AboutDialogViewModel>;
        [RunicViewContract("Compact")]
        public sealed partial class AboutDialogCompactView : RunicView<AboutDialogViewModel>;
        public sealed partial class SupportMenuView : RunicView<SupportMenuViewModel>;

        """;

    // The application: its own ViewModels present the library's, and use one of its enums.
    private const string ClientModuleApplication = """
        public sealed class MainViewModel : FixtureModel
        {
            public string Title => "";
            public SharedUi.Channel Channel { get; set; }
            public SharedUi.SupportMenuViewModel? Support { get; }
            [RunicViewContract("Compact")]
            public SharedUi.AboutDialogViewModel? About { get; }
            public SettingsViewModel? Settings { get; }
        }
        public sealed class SettingsViewModel : FixtureModel
        {
            public int Volume { get; set; }
        }
        public sealed partial class MainWindow : RunicWindow<MainViewModel>;
        public sealed partial class SettingsView : RunicView<SettingsViewModel>;

        """;

    // Before the mapping, each application declared the library ViewModels' Views itself.
    private const string ClientModuleApplicationViews = """
        public sealed partial class AboutDialogView : RunicView<SharedUi.AboutDialogViewModel>;
        [RunicViewContract("Compact")]
        public sealed partial class AboutDialogCompactView : RunicView<SharedUi.AboutDialogViewModel>;
        public sealed partial class SupportMenuView : RunicView<SharedUi.SupportMenuViewModel>;

        """;

    /// <summary>Compiles and generates the SharedUi client library; returns its assembly and generated TypeScript.</summary>
    private static async Task<(MetadataReference Reference, string TypeScript)> GenerateSharedUiAsync(string generator, string temporaryRoot)
    {
        var (exitCode, output, directory) = await RunGeneratorAsync(generator, temporaryRoot, "SharedUi",
            ClientLibrarySource("SharedUi", SharedUiViewModels + SharedUiViews), "--client-library").ConfigureAwait(false);
        Require(exitCode == 0, $"The SharedUi client library did not generate.\n{output}");
        return (MetadataReference.CreateFromFile(Path.Combine(directory, "FixtureSharedUi.dll")), Path.Combine(directory, "ts"));
    }

    private static Dictionary<string, string> Snapshot(string directory) => Directory.EnumerateFiles(directory)
        .ToDictionary(path => Path.GetFileName(path), File.ReadAllText, StringComparer.Ordinal);

