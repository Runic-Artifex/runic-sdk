    private static string Server()
    {
        var writer = new GenerationWriter();
        writer.Line("// <auto-generated />");
        writer.Line("import { AsyncLocalStorage } from \"node:async_hooks\";");
        writer.Line("import { baseLocale, configureLocaleResolver, resolveLocale } from \"./runtime.js\";");
        writer.Line("const localeStorage = new AsyncLocalStorage();");
        writer.Line("configureLocaleResolver(() => localeStorage.getStore() ?? baseLocale);");
        writer.Blank();
        writer.Line("export function runWithLocale(locale, operation) {");
        writer.Indent();
        writer.Line("if (typeof operation !== \"function\") throw new TypeError(\"A request operation is required.\");");
        writer.Line("return localeStorage.run(resolveLocale(locale), operation);");
        writer.Unindent();
        writer.Line("}");
        writer.Line("export function getRequestLocale() { return localeStorage.getStore() ?? baseLocale; }");
        return writer.ToString();
    }

