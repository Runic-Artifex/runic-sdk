        writer.Line("let next = index + 1; while (/\\s/.test(text[next] ?? \"\")) next++;");
        writer.Line("if (text[next] !== \":\") continue;");
        writer.Line("const scope = scopes.at(-1); if (!scope?.object) continue;");
        writer.Line("const key = JSON.parse(text.slice(start, index + 1)); if (scope.keys.has(key)) return true; scope.keys.add(key);");
        writer.Line("}");
        writer.Line("}");
        writer.Line("return false;");
        writer.Line("}");
        writer.Line("function failure(reason) { return { ok: false, reason }; }");
        return writer.ToString();
    }

