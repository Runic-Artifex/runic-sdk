    private static string Transport(CompiledTextCatalog catalog)
    {
        var writer = new GenerationWriter();
        writer.Line("// <auto-generated />");
        writer.Line("const catalog = " + GenerationSupport.JsonString(catalog.Id) + ";");
        writer.Line("const contractFingerprint = " + GenerationSupport.JsonString(catalog.Fingerprint) + ";");
        writer.Line("const contracts = Object.freeze({");
        writer.Indent();
        IReadOnlyList<CompiledTranslation> resources = GenerationSupport.OrderedResources(catalog.CanonicalResources);
        for (int index = 0; index < resources.Count; index++)
        {
            IReadOnlyList<CompiledTextPlaceholder> placeholders = GenerationSupport.OrderedPlaceholders(resources[index].Placeholders);
            var contract = new StringBuilder("{");
            for (int p = 0; p < placeholders.Count; p++)
            {
                if (p != 0) contract.Append(',');
                contract.Append(GenerationSupport.JsonString(placeholders[p].Name)).Append(':')
                    .Append(GenerationSupport.JsonString(PortableType(placeholders[p].Type)));
            }
            contract.Append('}');
            writer.Line(GenerationSupport.JsonString(resources[index].Key) + ": Object.freeze(" + contract + "),");
        }
        writer.Unindent();
        writer.Line("});");
        writer.Blank();
        writer.Line("export function decodeTextReference(value) {");
        writer.Indent();
        writer.Line("if (!isObject(value) || value.version !== 1) return failure(\"unsupported-version\");");
        writer.Line("if (value.catalog !== catalog) return failure(\"catalog-mismatch\");");
        writer.Line("if (value.contractFingerprint !== contractFingerprint) return failure(\"fingerprint-mismatch\");");
        writer.Line("if (typeof value.key !== \"string\" || value.key.length === 0 || value.key.length > 512 || !(value.key in contracts)) return failure(\"unknown-key\");");
        writer.Line("if (!isObject(value.arguments) || Object.keys(value.arguments).length > 32) return failure(\"invalid-arguments\");");
        writer.Line("const contract = contracts[value.key]; const names = Object.keys(contract).sort(); const actual = Object.keys(value.arguments).sort();");
        writer.Line("if (names.length !== actual.length || names.some((name, index) => name !== actual[index])) return failure(\"invalid-arguments\");");
        writer.Line("const argumentsValue = {};");
        writer.Line("for (const name of names) { const decoded = decodeArgument(value.arguments[name], contract[name]); if (!decoded.ok) return failure(`invalid-argument:${name}`); argumentsValue[name] = decoded.value; }");
        writer.Line("if (value.fallbackText !== undefined && (typeof value.fallbackText !== \"string\" || value.fallbackText.length > 65536)) return failure(\"invalid-fallback\");");
        writer.Line("return { ok: true, value: Object.freeze({ version: 1, catalog, contractFingerprint, key: value.key, arguments: Object.freeze(argumentsValue), fallbackText: value.fallbackText }) };");
        writer.Unindent();
        writer.Line("}");
        writer.Line("export function formatTextReference(reference, handlers, options) { const handler = handlers[reference.key]; if (typeof handler !== \"function\") { if (reference.fallbackText !== undefined) return reference.fallbackText; throw new RangeError(`No text-reference handler for '${reference.key}'.`); } return handler(reference.arguments, options); }");
