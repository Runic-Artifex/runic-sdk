        writer.Line("function sameNames(left, right) { const a = Object.keys(left).sort(), b = Object.keys(right).sort(); return a.length === b.length && a.every((name,index) => name === b[index]); }");
        writer.Line("function hasUnknownKeys(value, names) { const allowed = new Set(names); return Object.keys(value).some(name => !allowed.has(name)); }");
        writer.Line("function hasKeys(value, names) { return sameNames(value, Object.fromEntries(names.map(name => [name, true]))); }");
        writer.Line("function identifier(value) { return typeof value === \"string\" && /^[A-Za-z_][A-Za-z0-9_]*$/.test(value); }");
        writer.Line("function isObject(value) { return typeof value === \"object\" && value !== null && !Array.isArray(value); }");
        writer.Line("function deepFreeze(value) { if (value && typeof value === \"object\" && !Object.isFrozen(value)) { for (const child of Object.values(value)) deepFreeze(child); Object.freeze(value); } return value; }");
        writer.Line("function withinJsonDepth(bytes, maximum) { let depth = 0, quoted = false, escaped = false; for (const byte of bytes) { if (quoted) { if (escaped) escaped = false; else if (byte === 92) escaped = true; else if (byte === 34) quoted = false; } else if (byte === 34) quoted = true; else if (byte === 123 || byte === 91) { if (++depth > maximum) return false; } else if (byte === 125 || byte === 93) --depth; } return true; }");
        writer.Line("function hasDuplicateJsonProperties(text) {");
        writer.Line("const scopes = [];");
        writer.Line("for (let index = 0; index < text.length; index++) {");
        writer.Line("const character = text[index];");
        writer.Line("if (character === \"{\") scopes.push({ object: true, keys: new Set() });");
        writer.Line("else if (character === \"[\") scopes.push({ object: false });");
        writer.Line("else if (character === \"}\" || character === \"]\") scopes.pop();");
        writer.Line("else if (character === \"\\\"\") {");
        writer.Line("const start = index++; let escaped = false;");
        writer.Line("for (; index < text.length; index++) { if (escaped) escaped = false; else if (text[index] === \"\\\\\") escaped = true; else if (text[index] === \"\\\"\") break; }");
