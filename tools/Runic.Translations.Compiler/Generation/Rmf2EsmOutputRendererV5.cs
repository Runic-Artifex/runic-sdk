    private static TranslationGeneratedOutput Manifest(Rmf2ProjectV5 project, List<TranslationGeneratedOutput> outputs, string root)
    {
        var ordered = outputs.OrderBy(item => item.RelativePath, StringComparer.Ordinal).ToArray();
        var json = new StringBuilder("{\"webModuleManifestVersion\":" + TranslationOutputRenderer.WebModuleManifestVersion + ",\"esmAbiVersion\":" + TranslationOutputRenderer.EsmAbiVersion + ",\"rmf2RuntimeAbiVersion\":2,\"messageGrammarVersion\":5,\"profile\":\"rmf2-execution-v2\",\"generatedNameVersion\":1,\"catalog\":")
            .Append(GenerationSupport.JsonString(project.Id)).Append(",\"contractFingerprint\":").Append(GenerationSupport.JsonString(project.CallerFingerprint))
            .Append(",\"sourceHash\":").Append(GenerationSupport.JsonString(project.SourceHash))
            .Append(",\"entrypoints\":{\"messages\":\"messages.js\",\"types\":\"messages.d.ts\",\"runtime\":\"runtime.js\",\"server\":\"server.js\",\"transport\":\"transport.js\",\"dynamic\":\"dynamic.js\"},\"assets\":[");
        for (int index = 0; index < ordered.Length; index++)
        {
            if (index != 0) json.Append(','); TranslationGeneratedOutput output = ordered[index];
            json.Append("{\"path\":").Append(GenerationSupport.JsonString(output.RelativePath.Substring(root.Length)))
                .Append(",\"sha256\":").Append(GenerationSupport.JsonString(output.Sha256["sha256:".Length..]))
                .Append(",\"byteLength\":").Append(output.GetUtf8Bytes().Length).Append(",\"mediaType\":").Append(GenerationSupport.JsonString(output.MediaType)).Append('}');
        }
        json.Append("]}");
        return Output(TranslationGeneratedOutputKind.WebModuleManifestJson, root + "web-module-manifest-v3.json", "application/json", json.ToString());
    }

    private static string FileName(string key) => Rmf2GeneratedNamesV1.Identifier(key) + ".js";
    private static TranslationGeneratedOutput Output(TranslationGeneratedOutputKind kind, string path, string mediaType, string text) => new(kind, path, mediaType, text);
