    internal static IReadOnlyList<TranslationGeneratedOutput> Render(Rmf2ProjectV5 project)
    {
        string root = project.Id + ".esm-v5/";
        var messages = project.CanonicalMessages.OrderBy(item => item.Key, StringComparer.Ordinal).ToArray();
        var outputs = new List<TranslationGeneratedOutput>(messages.Length + 10)
        {
            Output(TranslationGeneratedOutputKind.EsmRuntime, root + "runtime.js", "text/javascript", Runtime(project)),
            Output(TranslationGeneratedOutputKind.EsmRuntimeTypes, root + "runtime.d.ts", "text/typescript", RuntimeTypes(project)),
            Output(TranslationGeneratedOutputKind.EsmTransport, root + "transport.js", "text/javascript", Transport(project)),
            Output(TranslationGeneratedOutputKind.EsmTransportTypes, root + "transport.d.ts", "text/typescript", TransportTypes(project)),
            Output(TranslationGeneratedOutputKind.EsmDynamic, root + "dynamic.js", "text/javascript", Dynamic()),
            Output(TranslationGeneratedOutputKind.EsmDynamicTypes, root + "dynamic.d.ts", "text/typescript", DynamicTypes(project)),
            Output(TranslationGeneratedOutputKind.EsmServer, root + "server.js", "text/javascript", Server()),
            Output(TranslationGeneratedOutputKind.EsmServerTypes, root + "server.d.ts", "text/typescript", ServerTypes()),
        };
        foreach (Rmf2MessageContractV5 message in messages)
            outputs.Add(Output(TranslationGeneratedOutputKind.EsmMessage, root + "messages/" + FileName(message.Key),
                "text/javascript", Message(project, message)));
        outputs.Add(Output(TranslationGeneratedOutputKind.EsmMessageNamespace, root + "messages/_index.js",
            "text/javascript", Namespace(messages)));
        outputs.Add(Output(TranslationGeneratedOutputKind.EsmMessagesIndex, root + "messages.js",
            "text/javascript", "// <auto-generated />\nexport { m } from \"./messages/_index.js\";\n"));
        outputs.Add(Output(TranslationGeneratedOutputKind.EsmMessagesTypes, root + "messages.d.ts",
            "text/typescript", MessageTypes(project, messages)));
        outputs.Add(Manifest(project, outputs, root));
        outputs.Sort(static (left, right) => StringComparer.Ordinal.Compare(left.RelativePath, right.RelativePath));
        return outputs;
    }

