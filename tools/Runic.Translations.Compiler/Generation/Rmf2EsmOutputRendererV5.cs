        return writer.ToString();
    }

    private static string ContractsJson(Rmf2ProjectV5 project, bool includeExtras)
    {
        using var stream = new MemoryStream();
        using (var writer = new Utf8JsonWriter(stream))
        {
            writer.WriteStartObject();
            IEnumerable<Rmf2MessageContractV5> messages = includeExtras
                ? project.CanonicalMessages.Concat(project.ExtraMessages)
                : project.CanonicalMessages;
            foreach (Rmf2MessageContractV5 message in messages.OrderBy(item => item.Key, StringComparer.Ordinal))
            {
                writer.WriteStartObject(message.Key); writer.WriteBoolean("structured", message.Structured); writer.WriteStartArray("inputs");
                foreach (Rmf2InputV5 input in message.Inputs) { writer.WriteStartObject(); writer.WriteString("name", input.Name); writer.WriteString("type", input.Type); writer.WriteEndObject(); }
                writer.WriteEndArray(); writer.WriteEndObject();
            }
            writer.WriteEndObject();
        }
        return Encoding.UTF8.GetString(stream.ToArray());
    }

    private static string Message(Rmf2ProjectV5 project, Rmf2MessageContractV5 contract)
    {
        var writer = new GenerationWriter();
        writer.Line("// <auto-generated />");
        writer.Line("import { formatCompiledMessage, freezeGeneratedMessage, getLocale, resolveLocale } from \"../runtime.js\";");
        writer.Line("const messages = Object.freeze(Object.assign(Object.create(null), {"); writer.Indent();
        foreach (Rmf2LocaleV5 locale in project.Locales.OrderBy(item => item.Tag, StringComparer.Ordinal))
        {
            Rmf2TranslationV5 resource = locale.ResolvedResources.Single(item => item.Key == contract.Key);
            string wrapper = "{\"contentLocale\":" + GenerationSupport.JsonString(resource.ContentLocale) + ",\"ast\":" +
                Rmf2MessageJsonV5.Serialize(resource.Message with { Inputs = contract.Inputs }) + "}";
            writer.Line(GenerationSupport.JsonString(locale.Tag) + ": freezeGeneratedMessage(" + GenerationSupport.JsonString(contract.Key) + ", JSON.parse(" + GenerationSupport.JsonString(wrapper) + ")), ");
        }
        writer.Unindent(); writer.Line("}));");
        string identifier = Rmf2GeneratedNamesV1.Identifier(contract.Key);
        writer.Line("export function " + identifier + "(" + (contract.Inputs.Count == 0 ? "options" : "inputs, options") + ") {"); writer.Indent();
        if (contract.Inputs.Count == 0) writer.Line("const inputs = Object.create(null);");
        writer.Line("const locale = resolveLocale(options?.locale ?? getLocale());");
        writer.Line("return formatCompiledMessage(" + GenerationSupport.JsonString(contract.Key) + ", messages[locale], inputs, locale);");
        writer.Unindent(); writer.Line("}");
        return writer.ToString();
    }

    private static string Namespace(IReadOnlyList<Rmf2MessageContractV5> messages)
    {
        var writer = new GenerationWriter(); writer.Line("// <auto-generated />");
        foreach (Rmf2MessageContractV5 message in messages)
            writer.Line("import { " + Rmf2GeneratedNamesV1.Identifier(message.Key) + " } from \"./" + FileName(message.Key) + "\";");
        writer.Line("const values = Object.create(null);");
        foreach (Rmf2MessageContractV5 message in messages)
            writer.Line("Object.defineProperty(values, " + GenerationSupport.JsonString(message.Key) + ", { value: " + Rmf2GeneratedNamesV1.Identifier(message.Key) + ", enumerable: true });");
        writer.Line("export const m = Object.freeze(values);");
        return writer.ToString();
    }

