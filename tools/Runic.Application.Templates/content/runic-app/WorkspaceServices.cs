using Microsoft.Extensions.DependencyInjection;
#if (viewModels == "reactiveui")
using Runic.Navigation.ReactiveUI;
#endif

namespace RunicWindowApp;

public static class WorkspaceServices
{
    // Program.cs opens the Window with these services; tests can build the same graph.
    public static IServiceCollection AddWorkspace(this IServiceCollection services)
    {
#if (viewModels == "reactiveui")
        services.AddRunicReactiveModelContext();
#endif
        services.AddScoped<WorkspaceViewModel>();
        services.AddScoped<WelcomeViewModel>();
        services.AddScoped<CounterViewModel>();
        // Generated by the build: the Window and View Bridges and the View locator.
        services.AddRunicViews();
        return services;
    }
}
