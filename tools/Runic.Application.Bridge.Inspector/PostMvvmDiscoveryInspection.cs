    private const string WindowBase = "Runic.Application.Bridge.PostMvvmFixture.ExplicitWindow`1";
    private const string ViewBase = "Runic.Application.Bridge.PostMvvmFixture.ExplicitView`1";
    private const string ViewBindingAttribute = "Runic.Application.Bridge.PostMvvmFixture.ExplicitViewBindingAttribute";
    private static readonly JsonSerializerOptions Json = new() { WriteIndented = true, PropertyNamingPolicy = JsonNamingPolicy.CamelCase };
    private static readonly JsonSerializerOptions CanonicalJson = new() { PropertyNamingPolicy = JsonNamingPolicy.CamelCase };

    internal static Task<int> RunAsync(string[] args)
    {
        if (args.Length != 10 || args[0] != "--assembly" || args[2] != "--ir" || args[4] != "--esm" || args[6] != "--adapter" || args[8] != "--ready")
            throw new ArgumentException("Post-MVVM discovery requires --assembly <path> --ir <path> --esm <path> --adapter <path> --ready <path>.");

        string assemblyPath = Path.GetFullPath(args[1]);
        string irPath = Path.GetFullPath(args[3]);
        string esmPath = Path.GetFullPath(args[5]);
        string adapterPath = Path.GetFullPath(args[7]);
        string readyPath = Path.GetFullPath(args[9]);
        if (!File.Exists(assemblyPath)) throw new FileNotFoundException("The compiled discovery assembly does not exist.", assemblyPath);
        if (new[] { irPath, esmPath, adapterPath, readyPath }.Distinct(StringComparer.Ordinal).Count() != 4)
            throw new ArgumentException("Post-MVVM output paths must be distinct.");

        // A failed inspection or render must never leave a previously published ready marker.
        File.Delete(readyPath);

        InspectionResult result = Inspect(assemblyPath);
        FixtureRuntime runtime = result.Bindings.Count == 0 ? CreateFixtureRuntime(result) : CreateMappedFixtureRuntime(result);
        // The browser-facing route and wire shape is part of this fixture's
        // discovered contract. Fingerprint it with the member metadata so a
        // ready manifest can never pair an old route map with a new adapter.
        string body = JsonSerializer.Serialize(new IrBody(
            "runic-sdk.post-mvvm-discovery-ir", 1, result.Assembly, result.Views, result.Models, result.Bindings, result.Contracts, runtime), CanonicalJson);
        string fingerprint = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(body))).ToLowerInvariant();

        string ir = JsonSerializer.Serialize(new IrDocument(
            "runic-sdk.post-mvvm-discovery-ir", 1, fingerprint, result.Assembly, result.Views, result.Models, result.Bindings, result.Contracts, runtime), Json);
        string esm = result.Bindings.Count == 0 ? RenderEsm(result, runtime, fingerprint) : RenderMappedEsm(result, runtime, fingerprint);
        string adapter = result.Bindings.Count == 0 ? RenderAdapter(result, fingerprint) : RenderMappedAdapter(result, fingerprint);
        string ready = JsonSerializer.Serialize(new ReadyDocument(
            "runic-sdk.post-mvvm-discovery-ready", 1, fingerprint,
            Path.GetFileName(irPath), Path.GetFileName(esmPath), Path.GetFileName(adapterPath)), Json);

        AtomicWrite(irPath, ir);
        AtomicWrite(esmPath, esm);
        AtomicWrite(adapterPath, adapter);
        AtomicWrite(readyPath, ready);
        Console.WriteLine($"POST_MVVM_SDK_DISCOVERY_EMITTED|views={result.Views.Count}|models={result.Models.Count}|esm=1|adapter=1");
        return Task.FromResult(0);
    }

    private static string RenderMappedEsm(InspectionResult result, FixtureRuntime runtime, string fingerprint)
    {
        ViewContract contract = result.Contracts.Single();
        string bindings = JsonSerializer.Serialize(result.Bindings, CanonicalJson);
        string fields = JsonSerializer.Serialize(contract.Fields, CanonicalJson);
        string routes = JsonSerializer.Serialize(runtime, CanonicalJson);
        string state = String.Join("\n", contract.Fields.Select(field => $"  readonly {field.Name}: string;"));
        return $$"""
            // <auto-generated /> Fixture-only declared View contract and Title wire shape;
            // application selection and mount remain host-owned.
            export const fingerprint = "{{fingerprint}}";
            export const declaredContext = {{JsonSerializer.Serialize(contract.DeclaredContext)}};
            export const bindings = {{bindings}} as const;
            export const fields = {{fields}} as const;
            export const commands = [] as const;
            export const runtime = {{routes}} as const;
            export const routeIds = { titleRead: "titleRead", titleWrite: "titleWrite" } as const;
            export interface ViewContextState {
            {{state}}
            }

            export type TitleReadRequest = Readonly<{ documentEpoch: string; presentationId: string }>;
            export type TitleWriteRequest = Readonly<{ documentEpoch: string; presentationId: string; title: string }>;
            export type TitleReply = Readonly<{ ok: true; title: string }> | Readonly<{ ok: false }>;
            export type TitleRouteId = typeof routeIds[keyof typeof routeIds];

            function exact(value: unknown, fields: readonly { readonly name: string; readonly codec: string }[], context: string): Record<string, unknown> {
              if (value === null || typeof value !== "object" || Array.isArray(value))
                throw new Error(`Invalid ${context}: expected an object.`);
              const object = value as Record<string, unknown>;
              const expected = fields.map(field => field.name).sort();
              const actual = Object.keys(object).sort();
              if (actual.length !== expected.length || actual.some((name, index) => name !== expected[index]))
                throw new Error(`Invalid ${context}: unexpected fields.`);
              for (const field of fields)
                if (typeof object[field.name] !== (field.codec === "boolean" ? "boolean" : "string"))
                  throw new Error(`Invalid ${context}: ${field.name} has the wrong type.`);
              return object;
            }

            function route(id: TitleRouteId) {
              const selected = runtime.routes.find(candidate => candidate.id === id);
              if (!selected) throw new Error(`Unknown declared Title route '${id}'.`);
              return selected;
            }

            export function routeName(referencePrefix: string, id: TitleRouteId): string {
              if (typeof referencePrefix !== "string" || referencePrefix.length === 0)
                throw new Error("A mapped View reference prefix is required.");
              return referencePrefix + route(id).suffix;
            }

            export function encodeTitleRequest(id: "titleRead", value: TitleReadRequest): TitleReadRequest;
            export function encodeTitleRequest(id: "titleWrite", value: TitleWriteRequest): TitleWriteRequest;
            export function encodeTitleRequest(id: TitleRouteId, value: unknown): Record<string, unknown> {
              return exact(value, route(id).request.fields, `${id} request`);
            }

            export function decodeTitleReply(id: TitleRouteId, value: unknown): TitleReply {
              if (value === null || typeof value !== "object" || Array.isArray(value))
                throw new Error(`Invalid ${id} reply: expected an object.`);
              const ok = (value as Record<string, unknown>).ok;
              if (typeof ok !== "boolean") throw new Error(`Invalid ${id} reply: ok must be a boolean.`);
              const variant = route(id).reply.variants.find(candidate => candidate.ok === ok);
              if (!variant) throw new Error(`Invalid ${id} reply: unknown variant.`);
              return exact(value, variant.wire.fields, `${id} reply`) as TitleReply;
            }
            """;
    }

    private static string RenderMappedAdapter(InspectionResult result, string fingerprint)
    {
        ViewContract contract = result.Contracts.Single();
        Field title = contract.Fields.Single(field => field.Name == "title" && field.Writable);
        string models = String.Join("\n", result.Bindings.Select(binding => binding.ConcreteModel).Distinct(StringComparer.Ordinal).Select(model => $$"""
                    internal static string Read{{title.ClrName}}(global::{{model}} model) => model.{{title.ClrName}};
                    internal static void Write{{title.ClrName}}(global::{{model}} model, string value) => model.{{title.ClrName}} = value;
                    internal static global::Runic.Application.Bridge.WindowBridgeAttachment AttachMappedFixtureRoutes(
                        global::Runic.Application.Bridge.IWindowBridgeTransport transport,
                        global::{{model}} model, string route,
                        global::Runic.Application.Bridge.WindowBridgeSession session,
                        global::System.Func<global::Runic.Application.Bridge.WindowBridgeReference> getReference) =>
                        AttachDeclaredTitleRoutes(transport, model, route, session, getReference);
            """));
        return $$"""
            // <auto-generated /> Fixture-only typed projection of the declared interface contract.
            #nullable enable
            namespace Runic.Application.Bridge.PostMvvmFixture.Generated
            {
                public static class PostMvvmDiscoveryAdapter
                {
                    public const string Stage = "post-mvvm-outer";
                    public const string Fingerprint = {{JsonSerializer.Serialize(fingerprint)}};
                    public const string View = {{JsonSerializer.Serialize(contract.View)}};
                    public const string DeclaredContext = {{JsonSerializer.Serialize(contract.DeclaredContext)}};
            {{models}}

                    private static global::Runic.Application.Bridge.WindowBridgeAttachment AttachDeclaredTitleRoutes(
                        global::Runic.Application.Bridge.IWindowBridgeTransport transport,
                        global::{{contract.DeclaredContext}} model, string route,
                        global::Runic.Application.Bridge.WindowBridgeSession session,
                        global::System.Func<global::Runic.Application.Bridge.WindowBridgeReference> getReference)
                    {
                        global::System.ArgumentNullException.ThrowIfNull(transport);
                        global::System.ArgumentNullException.ThrowIfNull(model);
                        global::System.ArgumentException.ThrowIfNullOrWhiteSpace(route);
                        global::System.ArgumentNullException.ThrowIfNull(session);
                        global::System.ArgumentNullException.ThrowIfNull(getReference);
                        var leases = new global::System.Collections.Generic.List<global::Runic.Application.Bridge.WindowBridgeEndpointLease>(2);
                        try
                        {
                            leases.Add(transport.Bind(route + ".{{title.Name}}.read", arguments =>
                            {
                                if (!TryReadTitleRequest(arguments.GetString(), false, out var epoch, out string? presentationId, out _)
                                    || !session.HasPresentation(getReference(), arguments.Connection, epoch!, presentationId!)) return Rejected();
                                return TitlePayload(model.{{title.ClrName}});
                            }));
                            leases.Add(transport.Bind(route + ".{{title.Name}}.write", arguments =>
                            {
                                if (!TryReadTitleRequest(arguments.GetString(), true, out var epoch, out string? presentationId, out string? title)
                                    || !session.HasPresentation(getReference(), arguments.Connection, epoch!, presentationId!)) return Rejected();
                                model.{{title.ClrName}} = title!;
                                return TitlePayload(model.{{title.ClrName}});
                            }));
                            return global::Runic.Application.Bridge.WindowBridgeAttachment.Create(leases.ToArray());
                        }
                        catch
                        {
                            foreach (global::Runic.Application.Bridge.WindowBridgeEndpointLease lease in leases) lease.Dispose();
                            throw;
                        }
                    }

                    private static bool TryReadTitleRequest(string payload, bool write,
                        out global::Runic.Application.Bridge.WindowBridgeDocumentEpoch? epoch,
                        out string? presentationId, out string? title)
                    {
                        epoch = null;
                        presentationId = title = null;
                        try
                        {
                            using global::System.Text.Json.JsonDocument document = global::System.Text.Json.JsonDocument.Parse(payload);
                            global::System.Text.Json.JsonElement request = document.RootElement;
                            if (request.ValueKind != global::System.Text.Json.JsonValueKind.Object) return false;
                            var found = new global::System.Collections.Generic.HashSet<string>(global::System.StringComparer.Ordinal);
                            foreach (global::System.Text.Json.JsonProperty property in request.EnumerateObject())
                                if (!found.Add(property.Name) || (property.Name != "documentEpoch" && property.Name != "presentationId"
                                    && (!write || property.Name != "{{title.Name}}"))) return false;
                            if (found.Count != (write ? 3 : 2)
                                || !request.TryGetProperty("documentEpoch", out var rawEpoch)
                                || rawEpoch.ValueKind != global::System.Text.Json.JsonValueKind.String
                                || !request.TryGetProperty("presentationId", out var rawPresentation)
                                || rawPresentation.ValueKind != global::System.Text.Json.JsonValueKind.String) return false;
                            presentationId = rawPresentation.GetString();
                            if (global::System.String.IsNullOrWhiteSpace(presentationId) || presentationId.Length > 128) return false;
                            if (write)
                            {
                                if (!request.TryGetProperty("{{title.Name}}", out var rawTitle)
                                    || rawTitle.ValueKind != global::System.Text.Json.JsonValueKind.String) return false;
                                title = rawTitle.GetString();
                                if (title is null) return false;
                            }
                            epoch = global::Runic.Application.Bridge.WindowBridgeDocumentEpoch.Create(rawEpoch.GetString()!);
                            return true;
                        }
                        catch (global::System.Text.Json.JsonException) { return false; }
                        catch (global::System.ArgumentException) { return false; }
                    }

                    private static string Rejected() => "{\"ok\":false}";

                    private static string TitlePayload(string title)
                    {
                        var bytes = new global::System.Buffers.ArrayBufferWriter<byte>();
                        using (var writer = new global::System.Text.Json.Utf8JsonWriter(bytes))
                        {
                            writer.WriteStartObject();
                            writer.WriteBoolean("ok", true);
                            writer.WriteString("{{title.Name}}", title);
                            writer.WriteEndObject();
                            writer.Flush();
                        }
                        return global::System.Text.Encoding.UTF8.GetString(bytes.WrittenSpan);
                    }
                }
            }
            """;
    }

    private static FixtureRuntime CreateMappedFixtureRuntime(InspectionResult result)
    {
        ViewContract contract = result.Contracts.Single();
        Field title = contract.Fields.Single(field => field.Name == "title" && field.Writable && field.Codec == "string");
        WireField epoch = new("documentEpoch", "document-epoch");
        WireField presentation = new("presentationId", "string");
        WireField ok = new("ok", "boolean");
        WireField value = new(title.Name, title.Codec);
        return new FixtureRuntime("runic-sdk.post-mvvm-fixture-runtime", 3, "mounted-reference-prefix", [
            new Route("titleRead", contract.DeclaredContext, title.Name, "field-read", "." + title.Name + ".read",
                new WireObject([epoch, presentation]),
                new WireReply([new WireVariant("accepted", true, new WireObject([ok, value])), new WireVariant("rejected", false, new WireObject([ok]))])),
            new Route("titleWrite", contract.DeclaredContext, title.Name, "field-write", "." + title.Name + ".write",
                new WireObject([epoch, presentation, value]),
                new WireReply([new WireVariant("accepted", true, new WireObject([ok, value])), new WireVariant("rejected", false, new WireObject([ok]))])),
        ]);
    }

    private static string RenderEsm(InspectionResult result, FixtureRuntime runtime, string fingerprint)
    {
        Model model = result.Models.Single();
        bool hasCheckedTitleWrite = runtime.Routes.Any(route => route.Id == "titleWriteChecked");
        string snapshotRouteId = hasCheckedTitleWrite ? "\n              titleSnapshot: \"titleSnapshot\"," : String.Empty;
        string checkedRouteId = hasCheckedTitleWrite ? "\n              titleWriteChecked: \"titleWriteChecked\"," : String.Empty;
        string checkedModelRouteId = hasCheckedTitleWrite ? " | typeof routeIds.titleSnapshot | typeof routeIds.titleWriteChecked" : String.Empty;
        string checkedRequestOverload = hasCheckedTitleWrite
            ? "\n            export function encodeRouteRequest(routeId: \"titleWriteChecked\", value: TitleWriteCheckedRequest): TitleWriteCheckedRequest;"
            : String.Empty;
        string snapshotRequestOverload = hasCheckedTitleWrite
            ? "\n            export function encodeRouteRequest(routeId: \"titleSnapshot\", value: TitleReadRequest): TitleReadRequest;"
            : String.Empty;
        string checkedReplyOverload = hasCheckedTitleWrite
            ? "\n            export function decodeRouteReply(routeId: \"titleWriteChecked\", value: unknown): TitleWriteReceipt;"
            : String.Empty;
        string snapshotReplyOverload = hasCheckedTitleWrite
            ? "\n            export function decodeRouteReply(routeId: \"titleSnapshot\", value: unknown): TitleSnapshotReply;"
            : String.Empty;
        string fields = String.Join("\n", model.Fields.Select(field => $"  readonly {field.Name}: string;"));
        string commands = String.Join("\n", model.Commands.Select(command => command.Kind switch
        {
            "toolkit-async-relay" => $"  readonly {command.Name}: () => Promise<void>;",
            "reactive-command-string-string" => $"  readonly {command.Name}: (value: string) => Promise<string>;",
            _ => throw new InvalidOperationException($"Unsupported fixture command {command.Kind}.")
        }));
        string viewMetadata = JsonSerializer.Serialize(result.Views, CanonicalJson);
        string fieldMetadata = JsonSerializer.Serialize(model.Fields, CanonicalJson);
        string commandMetadata = JsonSerializer.Serialize(model.Commands, CanonicalJson);
        string runtimeMetadata = JsonSerializer.Serialize(runtime, CanonicalJson);
        return $$"""
            // <auto-generated /> Internal post-MVVM fixture contract. It describes
            // model-relative and Window-owned routes with strict wire objects;
            // it does not mount a model or resolve an application reference.
            export const fingerprint = "{{fingerprint}}";
            export const views = {{viewMetadata}} as const;
            export const fields = {{fieldMetadata}} as const;
            export const commands = {{commandMetadata}} as const;
            export const runtime = {{runtimeMetadata}} as const;
            export const routeIds = {
              titleRead: "titleRead",
            {{snapshotRouteId}}
              titleWrite: "titleWrite",
            {{checkedRouteId}}
              saveStart: "saveStart",
              saveStatus: "saveStatus",
              saveWait: "saveWait",
              refresh: "refresh",
            } as const;

            export interface ViewModelState {
            {{fields}}
            }

            export interface ViewModelCommands {
            {{commands}}
            }

            export type RuntimeRouteId = typeof routeIds[keyof typeof routeIds];
            export type ModelRouteId = typeof routeIds.titleRead | typeof routeIds.titleWrite{{checkedModelRouteId}} | typeof routeIds.saveStart | typeof routeIds.refresh;
            export type WindowRouteId = typeof routeIds.saveStatus | typeof routeIds.saveWait;
            export type TitleReadRequest = Readonly<{ documentEpoch: string; presentationId: string }>;
            export type TitleWriteRequest = Readonly<{ documentEpoch: string; presentationId: string; title: string }>;
            export type TitleSnapshot = Readonly<{ value: string; version: number; generation: string }>;
            export type TitleSnapshotReply = Readonly<{ ok: true; current: TitleSnapshot }> | Readonly<{ ok: false }>;
            export type TitleWriteCheckedRequest = Readonly<{ documentEpoch: string; presentationId: string; requestId: string; title: string; expected: TitleSnapshot }>;
            export type TitleWriteReceipt =
              | Readonly<{ ok: true; kind: "applied"; current: TitleSnapshot; error: null }>
              | Readonly<{ ok: false; kind: "conflict" | "expired"; current: TitleSnapshot; error: null }>
              | Readonly<{ ok: false; kind: "committed-with-error" | "rejected"; current: TitleSnapshot; error: string }>;
            export type SaveStartRequest = Readonly<{ documentEpoch: string; presentationId: string; requestId: string }>;
            export type SaveObservationRequest = Readonly<{ referenceId: string; documentEpoch: string; requestId: string }>;
            export type RefreshRequest = Readonly<{ documentEpoch: string; presentationId: string; value: string }>;
            export type TitleReply = Readonly<{ ok: true; title: string }> | Readonly<{ ok: false }>;
            export type OperationKind = "unknown" | "running" | "succeeded" | "failed" | "cancelled" | "rejected" | "expired";
            export type SaveStatusReply = Readonly<{ requestId: string | null; kind: OperationKind; state: string | null; error: string | null }>;
            export type SaveStartReply = SaveStatusReply & Readonly<{ accepted: boolean }>;
            export type RefreshReply = Readonly<{ ok: true; value: string }> | Readonly<{ ok: false }>;

            type WireObject = Record<string, unknown>;

            function route(routeId: RuntimeRouteId) {
              const selected = runtime.routes.find(candidate => candidate.id === routeId);
              if (!selected) throw new Error(`Unknown generated route '${routeId}'.`);
              return selected;
            }

            function object(value: unknown, context: string): WireObject {
              if (value === null || typeof value !== "object" || Array.isArray(value))
                throw new Error(`Invalid ${context}: expected an object.`);
              return value as WireObject;
            }

            function exact(value: WireObject, fields: readonly { readonly name: string; readonly codec: string }[], context: string): WireObject {
              const expected = fields.map(field => field.name).sort();
              const actual = Object.keys(value).sort();
              if (actual.length !== expected.length || actual.some((key, index) => key !== expected[index]))
                throw new Error(`Invalid ${context}: unexpected fields.`);
              for (const field of fields) {
                const current = value[field.name];
                if (field.codec === "boolean" ? typeof current !== "boolean"
                    : field.codec === "nullable-string" ? current !== null && typeof current !== "string"
                    : field.codec === "operation-kind" ? !["unknown", "running", "succeeded", "failed", "cancelled", "rejected", "expired"].includes(current as string)
                    : field.codec === "title-write-kind" ? !["applied", "conflict", "expired", "committed-with-error", "rejected"].includes(current as string)
                    : field.codec === "title-snapshot" ? !titleSnapshot(current)
                    : typeof current !== "string")
                  throw new Error(`Invalid ${context}: ${field.name} has the wrong type.`);
              }
              return value;
            }

            function titleSnapshot(value: unknown): value is TitleSnapshot {
              if (value === null || typeof value !== "object" || Array.isArray(value)) return false;
              const record = value as Record<string, unknown>;
              return Object.keys(record).length === 3 && typeof record.value === "string"
                && typeof record.version === "number" && Number.isSafeInteger(record.version) && record.version >= 0
                && typeof record.generation === "string" && /^[0-9a-f]{32}$/.test(record.generation);
            }

            export function routeName(referencePrefix: string, routeId: ModelRouteId): string {
              if (typeof referencePrefix !== "string" || referencePrefix.length === 0)
                throw new Error("A generated route reference prefix is required.");
              const selected = route(routeId);
              if (selected.scope !== "model") throw new Error("A Window route cannot use a model reference prefix.");
              return referencePrefix + selected.suffix;
            }

            export function windowRouteName(routeId: WindowRouteId): string {
              const selected = route(routeId);
              if (selected.scope !== "window") throw new Error("A model route cannot use a Window route name.");
              return selected.suffix;
            }

            export function encodeRouteRequest(routeId: "titleRead", value: TitleReadRequest): TitleReadRequest;
            {{snapshotRequestOverload}}
            export function encodeRouteRequest(routeId: "titleWrite", value: TitleWriteRequest): TitleWriteRequest;
            {{checkedRequestOverload}}
            export function encodeRouteRequest(routeId: "saveStart", value: SaveStartRequest): SaveStartRequest;
            export function encodeRouteRequest(routeId: "saveStatus" | "saveWait", value: SaveObservationRequest): SaveObservationRequest;
            export function encodeRouteRequest(routeId: "refresh", value: RefreshRequest): RefreshRequest;
            export function encodeRouteRequest(routeId: RuntimeRouteId, value: unknown): WireObject {
              return exact(object(value, `${routeId} request`), route(routeId).request.fields, `${routeId} request`);
            }

            export function decodeRouteReply(routeId: "titleRead" | "titleWrite", value: unknown): TitleReply;
            {{snapshotReplyOverload}}
            {{checkedReplyOverload}}
            export function decodeRouteReply(routeId: "saveStart", value: unknown): SaveStartReply;
            export function decodeRouteReply(routeId: "saveStatus" | "saveWait", value: unknown): SaveStatusReply;
            export function decodeRouteReply(routeId: "refresh", value: unknown): RefreshReply;
            export function decodeRouteReply(routeId: RuntimeRouteId, value: unknown): WireObject {
              const reply = object(value, `${routeId} reply`);
              if (routeId === routeIds.saveStart || routeId === routeIds.saveStatus || routeId === routeIds.saveWait)
                return exact(reply, route(routeId).reply.variants[0].wire.fields, `${routeId} reply`);
              if (typeof reply.ok !== "boolean") throw new Error(`Invalid ${routeId} reply: ok must be a boolean.`);
              const variant = route(routeId).reply.variants.find(candidate => candidate.ok === reply.ok);
              if (!variant) throw new Error(`Invalid ${routeId} reply: unknown variant.`);
              return exact(reply, variant.wire.fields, `${routeId} reply`);
            }
            """;
    }

    private static FixtureRuntime CreateFixtureRuntime(InspectionResult result)
    {
        Model model = result.Models.Single();
        Field title = model.Fields.Single(field => field.Name == "title" && field.Codec == "string");
        Command save = model.Commands.Single(command => command.Kind == "toolkit-async-relay");
        Command refresh = model.Commands.Single(command => command.Kind == "reactive-command-string-string");
        WireField documentEpoch = new("documentEpoch", "document-epoch");
        WireField referenceId = new("referenceId", "string");
        WireField presentationId = new("presentationId", "string");
        WireField ok = new("ok", "boolean");
        WireField titleField = new(title.Name, title.Codec);
        WireField value = new("value", "string");
        WireField requestId = new("requestId", "nullable-string");
        WireField kind = new("kind", "operation-kind");
        WireField state = new("state", "nullable-string");
        WireField error = new("error", "nullable-string");
        WireField accepted = new("accepted", "boolean");
        WireField expected = new("expected", "title-snapshot");
        WireField current = new("current", "title-snapshot");
        WireField writeKind = new("kind", "title-write-kind");
        return new FixtureRuntime("runic-sdk.post-mvvm-fixture-runtime", 3, "mounted-reference-prefix", [
            new Route("titleRead", model.Name, title.Name, "field-read", "." + title.Name + ".read",
                new WireObject([documentEpoch, presentationId]),
                new WireReply([new WireVariant("accepted", true, new WireObject([ok, titleField])), new WireVariant("rejected", false, new WireObject([ok]))])),
            new Route("titleSnapshot", model.Name, title.Name, "field-snapshot", "." + title.Name + ".snapshot",
                new WireObject([documentEpoch, presentationId]),
                new WireReply([new WireVariant("accepted", true, new WireObject([ok, current])), new WireVariant("rejected", false, new WireObject([ok]))])),
            new Route("titleWrite", model.Name, title.Name, "field-write", "." + title.Name + ".write",
                new WireObject([documentEpoch, presentationId, titleField]),
                new WireReply([new WireVariant("accepted", true, new WireObject([ok, titleField])), new WireVariant("rejected", false, new WireObject([ok]))])),
