    private static InspectionResult Inspect(string assemblyPath)
    {
        using var context = new MetadataLoadContext(new PathAssemblyResolver(MetadataClosure(assemblyPath)));
        Assembly assembly = context.LoadFromAssemblyPath(assemblyPath);
        Type[] types = assembly.GetTypes();
        Candidate[] candidates = types
            .Where(type => type is { IsClass: true, IsAbstract: false })
            .Select(type => Candidate.TryCreate(type))
            .Where(candidate => candidate is not null)
            .Cast<Candidate>()
            .OrderBy(candidate => candidate.Kind, StringComparer.Ordinal)
            .ThenBy(candidate => candidate.Name, StringComparer.Ordinal)
            .ToArray();

        Candidate[] openCandidates = candidates.Where(candidate => candidate.IsOpenGeneric).ToArray();
        if (openCandidates.Length > 0)
            throw new PostMvvmDiscoveryDiagnosticException("RUNICPM001",
                $"Explicit Window/View candidates must be closed types in this fixture. Open candidates: {Names(openCandidates)}. Close or remove these candidate types.");

        Candidate[] windows = candidates.Where(candidate => candidate.Kind == "window").ToArray();
        Candidate[] views = candidates.Where(candidate => candidate.Kind == "view").ToArray();
        if (views.Length != 1 || windows.Length == 0)
            throw new PostMvvmDiscoveryDiagnosticException("RUNICPM002",
                $"This fixture requires at least one explicit Window and exactly one explicit View; found windows={windows.Length} [{Names(windows)}], views={views.Length} [{Names(views)}]. Select one View candidate.");

        // An explicitly selected View contract must not change merely because
        // the application adds another Window. The unbound single-Window
        // interface probe below deliberately retains its concrete projection.
        bool hasExplicitBindings = CustomAttributeData.GetCustomAttributes(views[0].ClrType)
            .Any(attribute => attribute.AttributeType.FullName == ViewBindingAttribute);
        if (windows.Length > 1 || hasExplicitBindings)
            return InspectMappedView(assembly, candidates, windows, views[0]);
        if (views.Length != 1)
            throw new InvalidOperationException("The fixture did not have one View.");

        Candidate window = windows[0];
        Candidate view = views[0];
        string modelName = window.DeclaredContext;
        if (!view.ContextType.IsAssignableFrom(window.ContextType))
            throw new PostMvvmDiscoveryDiagnosticException("RUNICPM003",
                $"Explicit Window {window.Name} binds {window.DeclaredContext}, but View {view.Name} declares context {view.DeclaredContext}, which does not accept that concrete model. Select a compatible View context for this fixture pair.");

        if (!window.ContextType.IsClass || window.ContextType.IsAbstract || window.ContextType.ContainsGenericParameters || window.ContextType.Assembly != assembly)
            throw new PostMvvmDiscoveryDiagnosticException("RUNICPM004",
                $"The Window binds {modelName}, which is not one concrete, closed view model class in the compiled fixture assembly. Declare a concrete fixture model on the Window before selecting a compatible View context.");
        Type model = window.ContextType;
        Model discovered = DiscoverModel(model);
        Field[] fields = discovered.Fields.ToArray();
        Command[] commands = discovered.Commands.ToArray();

        if (!fields.Any(field => field.Name == "title") || !commands.Any(command => command.Kind == "toolkit-async-relay") || !commands.Any(command => command.Kind == "reactive-command-string-string"))
            throw new InvalidOperationException("The compiled fixture did not expose the expected CommunityToolkit and ReactiveUI members.");

        return new InspectionResult(
            assembly.GetName().Name ?? throw new InvalidOperationException("The discovery assembly has no name."),
            candidates.Select(candidate => new View(candidate.Kind, candidate.Name, candidate.DeclaredContext, modelName)).ToArray(),
            [new Model(modelName, fields, commands)], [], []);
    }

    private static InspectionResult InspectMappedView(Assembly assembly, Candidate[] candidates, Candidate[] windows, Candidate view)
    {
        if (!view.ContextType.IsInterface)
            throw new PostMvvmDiscoveryDiagnosticException("RUNICPM002",
                $"Explicit View mapping requires an interface context and selection keys; View {view.Name} declares {view.DeclaredContext}.");

        CustomAttributeData[] declarations = CustomAttributeData.GetCustomAttributes(view.ClrType)
            .Where(attribute => attribute.AttributeType.FullName == ViewBindingAttribute)
            .ToArray();
        if (declarations.Length == 0)
            throw new PostMvvmDiscoveryDiagnosticException("RUNICPM002",
                $"View {view.Name} has no explicit selection keys. Declare each allowed concrete model on the View.");
        ViewBinding[] bindings = declarations.Select(declaration =>
        {
            if (declaration.ConstructorArguments.Count != 2 || declaration.ConstructorArguments[0].Value is not string key ||
                declaration.ConstructorArguments[1].Value is not Type type)
                throw new InvalidOperationException("The fixture mapping attribute has an invalid compiled shape.");
            return new ViewBinding(view.Name, view.DeclaredContext, key, TypeName(type));
        }).OrderBy(binding => binding.SelectionKey, StringComparer.Ordinal)
          .ThenBy(binding => binding.ConcreteModel, StringComparer.Ordinal).ToArray();

        if (bindings.Any(binding => String.IsNullOrWhiteSpace(binding.SelectionKey)) ||
            bindings.GroupBy(binding => binding.SelectionKey, StringComparer.Ordinal).Any(group => group.Count() != 1))
            throw new PostMvvmDiscoveryDiagnosticException("RUNICPM005",
                $"View {view.Name} has blank or duplicate selection keys. Give every allowed concrete model a distinct nonblank key.");

        var windowModels = windows.Select(window => window.DeclaredContext).ToHashSet(StringComparer.Ordinal);
        if (windowModels.Count != windows.Length)
            throw new PostMvvmDiscoveryDiagnosticException("RUNICPM007",
                $"Windows select the same concrete model for View {view.Name}. Give each Window a distinct model selection in this fixture.");
        foreach (Candidate window in windows)
            if (!window.ContextType.IsClass || window.ContextType.IsAbstract || window.ContextType.ContainsGenericParameters || window.ContextType.Assembly != assembly)
                throw new PostMvvmDiscoveryDiagnosticException("RUNICPM004",
                    $"Window {window.Name} binds {window.DeclaredContext}, which is not a concrete, closed model in the compiled fixture assembly.");

        foreach (ViewBinding binding in bindings)
        {
            Type mapped = assembly.GetType(binding.ConcreteModel) ??
                throw new PostMvvmDiscoveryDiagnosticException("RUNICPM006", $"Selection key {binding.SelectionKey} names a model outside the compiled fixture assembly.");
            if (!mapped.IsClass || mapped.IsAbstract || !view.ContextType.IsAssignableFrom(mapped))
                throw new PostMvvmDiscoveryDiagnosticException("RUNICPM006",
                    $"Selection key {binding.SelectionKey} maps {binding.ConcreteModel}, which does not implement View {view.Name}'s declared context {view.DeclaredContext}.");
        }
        string[] unmapped = windows.Select(window => window.DeclaredContext)
            .Where(model => !bindings.Any(binding => binding.ConcreteModel == model)).ToArray();
        string[] unused = bindings.Select(binding => binding.ConcreteModel)
            .Where(model => !windowModels.Contains(model)).ToArray();
        if (unmapped.Length > 0 || unused.Length > 0)
            throw new PostMvvmDiscoveryDiagnosticException("RUNICPM007",
                $"View {view.Name} mappings do not match Window selections; unmapped [{String.Join(", ", unmapped)}], unused [{String.Join(", ", unused)}]. Declare exactly one selection key for each selected model.");

        Field[] contractFields = view.ContextType.GetProperties(BindingFlags.Instance | BindingFlags.Public)
            .Where(property => property.PropertyType.FullName == "System.String" && property.CanRead)
            .Select(property => new Field(ToCamelCase(property.Name), "string", property.CanWrite, property.Name))
            .OrderBy(field => field.Name, StringComparer.Ordinal).ToArray();
        Command[] contractCommands = view.ContextType.GetProperties(BindingFlags.Instance | BindingFlags.Public)
            .Select(Command.TryCreate).Where(command => command is not null).Cast<Command>()
            .OrderBy(command => command.Name, StringComparer.Ordinal).ToArray();
        if (contractFields.Length != 1 || contractFields[0].Name != "title" || !contractFields[0].Writable || contractCommands.Length != 0)
            throw new InvalidOperationException("The fixture interface must declare only a writable Title and no commands.");

        return new InspectionResult(
            assembly.GetName().Name ?? throw new InvalidOperationException("The discovery assembly has no name."),
            candidates.Select(candidate => new View(candidate.Kind, candidate.Name, candidate.DeclaredContext,
                candidate.Kind == "window" ? candidate.DeclaredContext : null)).ToArray(),
            windows.Select(window => DiscoverModel(window.ContextType)).ToArray(), bindings,
            [new ViewContract(view.Name, view.DeclaredContext, contractFields, contractCommands)]);
    }

    private static Model DiscoverModel(Type model)
    {
        Field[] fields = model.GetProperties(BindingFlags.Instance | BindingFlags.Public)
            .Where(property => property is { CanRead: true, CanWrite: true } && property.PropertyType.FullName == "System.String")
            .Select(property => new Field(ToCamelCase(property.Name), "string", true, property.Name))
            .OrderBy(field => field.Name, StringComparer.Ordinal).ToArray();
        Command[] commands = model.GetProperties(BindingFlags.Instance | BindingFlags.Public)
            .Select(Command.TryCreate).Where(command => command is not null).Cast<Command>()
            .OrderBy(command => command.Name, StringComparer.Ordinal).ToArray();
        return new Model(TypeName(model), fields, commands);
    }

    private static IEnumerable<string> MetadataClosure(string assemblyPath)
    {
        string directory = Path.GetDirectoryName(assemblyPath) ?? throw new InvalidOperationException("The compiled assembly has no directory.");
        string? trusted = AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") as string;
        if (String.IsNullOrWhiteSpace(trusted)) throw new InvalidOperationException("The runtime did not expose its trusted platform assembly closure.");
        return Directory.EnumerateFiles(directory, "*.dll")
            .Concat(trusted.Split(Path.PathSeparator, StringSplitOptions.RemoveEmptyEntries))
            .Append(assemblyPath)
            .Distinct(StringComparer.OrdinalIgnoreCase);
    }

    private static string TypeName(Type type) => type.FullName ?? throw new InvalidOperationException("A fixture type has no metadata name.");

    private static string Names(IEnumerable<Candidate> candidates) => String.Join(", ", candidates.Select(candidate => candidate.Name));

    private static string ToCamelCase(string value) => Char.ToLowerInvariant(value[0]) + value[1..];

    private static void AtomicWrite(string path, string content)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path) ?? throw new InvalidOperationException("Output path has no directory."));
        string temporary = path + ".tmp";
        File.WriteAllText(temporary, content + Environment.NewLine, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        File.Move(temporary, path, overwrite: true);
    }

    private sealed record InspectionResult(string Assembly, IReadOnlyList<View> Views, IReadOnlyList<Model> Models,
        IReadOnlyList<ViewBinding> Bindings, IReadOnlyList<ViewContract> Contracts);
    private sealed record Candidate(string Kind, string Name, string DeclaredContext, Type ContextType, Type ClrType, bool IsOpenGeneric)
    {
        internal static Candidate? TryCreate(Type type)
        {
            for (Type? current = type.BaseType; current is not null; current = current.BaseType)
            {
                if (!current.IsGenericType) continue;
                string? definition = current.GetGenericTypeDefinition().FullName;
                string kind = definition == WindowBase ? "window" : definition == ViewBase ? "view" : String.Empty;
                if (String.IsNullOrEmpty(kind)) continue;
                Type model = current.GetGenericArguments()[0];
                return new Candidate(kind, TypeName(type), model.FullName ?? model.Name, model, type, type.ContainsGenericParameters || model.ContainsGenericParameters);
            }
            return null;
        }
    }

    private sealed record Field(string Name, string Codec, bool Writable, [property: JsonIgnore] string ClrName);
    private sealed record Command(string Name, string Kind, [property: JsonIgnore] string ClrName)
    {
        internal static Command? TryCreate(PropertyInfo property)
        {
            if (property.PropertyType.FullName == "CommunityToolkit.Mvvm.Input.IAsyncRelayCommand" || property.PropertyType.GetInterfaces().Any(type => type.FullName == "CommunityToolkit.Mvvm.Input.IAsyncRelayCommand"))
                return new Command(ToCamelCase(property.Name), "toolkit-async-relay", property.Name);
            if (property.PropertyType.IsGenericType && property.PropertyType.GetGenericTypeDefinition().FullName == "ReactiveUI.ReactiveCommand`2" &&
                property.PropertyType.GetGenericArguments() is [Type input, Type output] &&
                input.FullName == "System.String" && output.FullName == "System.String")
                return new Command(ToCamelCase(property.Name), "reactive-command-string-string", property.Name);
            return null;
        }
    }

    private sealed record View(string Kind, string Name, string DeclaredContext, string? ConcreteModel);
    private sealed record ViewBinding(string View, string DeclaredContext, string SelectionKey, string ConcreteModel);
    private sealed record ViewContract(string View, string DeclaredContext, IReadOnlyList<Field> Fields, IReadOnlyList<Command> Commands);
    private sealed record Model(string Name, IReadOnlyList<Field> Fields, IReadOnlyList<Command> Commands);
    private sealed record WireField(string Name, string Codec);
    private sealed record WireObject(IReadOnlyList<WireField> Fields);
    private sealed record WireVariant(string Name, bool? Ok, WireObject Wire);
    private sealed record WireReply(IReadOnlyList<WireVariant> Variants);
    private sealed record Route(string Id, string Model, string Member, string Kind, string Suffix, WireObject Request, WireReply Reply, string Scope = "model");
    private sealed record FixtureRuntime(string Format, int FormatVersion, string ReferencePrefix, IReadOnlyList<Route> Routes);
    private sealed record IrBody(string Format, int FormatVersion, string Assembly, IReadOnlyList<View> Views, IReadOnlyList<Model> Models,
        IReadOnlyList<ViewBinding> Bindings, IReadOnlyList<ViewContract> Contracts, FixtureRuntime Runtime);
    private sealed record IrDocument(string Format, int FormatVersion, string Fingerprint, string Assembly, IReadOnlyList<View> Views, IReadOnlyList<Model> Models,
        IReadOnlyList<ViewBinding> Bindings, IReadOnlyList<ViewContract> Contracts, FixtureRuntime Runtime);
    private sealed record ReadyDocument(string Format, int FormatVersion, string Fingerprint, string Ir, string Esm, string Adapter);
